// hyprWriter is Hyprland's config writer: axiom's layer as Hyprland's Lua
// (docs/dev/hyprland/config-modes.md):
//
//	detached  evaluated at runtime; binds on keys already taken are skipped
//	included  the module at $XDG_STATE_HOME/axiom/hyprland.lua, which the
//	          user's hyprland.lua loads
//	managed   ~/.config/hypr/hyprland.lua itself, loading user/*.lua after it
type hyprWriter struct {
	env
	ipc     *ipc.Hypr
	runtime runtimeLayer
}

const hyprHeader = "-- Generated by axiom"

func newHypr(e env, h *ipc.Hypr) *hyprWriter {
	return &hyprWriter{env: e, ipc: h, runtime: runtimeLayer{logf: e.logf, configName: "Hyprland"}}
}

func (w *hyprWriter) header() string        { return hyprHeader }
func (w *hyprWriter) takeoverKind() string  { return "hyprland" }
func (w *hyprWriter) liveByFile() bool      { return false }
func (w *hyprWriter) takesBack(string) bool { return false }

func (w *hyprWriter) dir() string { return w.configHome() + "/hypr/" }

func (w *hyprWriter) includePath() string { return w.stateDir + "hyprland.lua" }

func (w *hyprWriter) includeLines() string {
	return "local ok, axiom = pcall(dofile, " + render.LuaString(w.includePath()) + ")\nif ok then axiom.setup() end"
}

func (w *hyprWriter) autostartLines(in Inputs) string {
	return `hl.on("hyprland.start", function() hl.exec_cmd(` + render.LuaString(startCommand(in)) + `) end) -- axiom`
}

func (w *hyprWriter) files(in Inputs) files {
	managed := w.dir() + "hyprland.lua"
	return files{
		ConfigDir: w.dir(), IncludePath: w.includePath(), ManagedPath: managed, UserDir: w.dir() + "user", UserFiles: w.dir() + "user/*.lua",
		IncludeLines: w.includeLines(), AutostartLines: w.autostartLines(in),
		// I18n's in CompositorConfigManager
		IncludeTarget: jsonx.Obj("title", "Load axiom's module", "file", managed, "text", w.includeLines(), "place", "start",
			"comment", "--", "accept", `axiom\.setup\(`,
			"note", "Adds the lines at the top, so your own settings after them win over axiom's."),
		AutostartTarget: jsonx.Obj("title", "Start axiom", "file", managed, "text", w.autostartLines(in), "place", "end",
			"comment", "--", "accept", in.str("startPattern"),
			"note", "Adds the line at the end: Hyprland starts axiom with every session."),
	}
}

func (w *hyprWriter) problems(in Inputs) problems {
	f := w.files(in)
	return problems{
		NotIncluded: `Compositor mode is "included", but hyprland.lua doesn't load ` + f.IncludePath + "; add:\n" + f.IncludeLines,
		NotManaged:  `Compositor mode is "managed", but ` + f.ManagedPath + " isn't loaded (see hyprctl configerrors)",
	}
}

func (w *hyprWriter) monitorPattern() (*regexp.Regexp, string) {
	return regexp.MustCompile(`^[[:space:]]*hl\.monitor[[:space:]]*\(`), "*.lua"
}

func (w *hyprWriter) complete(in Inputs, bind any) bool {
	return w.tables.BindLua(bind, in.get("ctx")) != ""
}

func (w *hyprWriter) stripsLua(in Inputs) []string {
	return render.StripsLua(in.get("strips"), w.schemaOf("Workspaces"), in.get("stripOptions"))
}

// monitorCalls are the profile for what's connected (buildInputs'
// monitorCalls, applied live by the manager's profile switch too, so a
// reload keeps it), or, until the outputs are read, what the file says
func (w *hyprWriter) monitorCalls(in Inputs, path string) any {
	if calls := in.get("monitorCalls"); calls != nil {
		return calls
	}
	return strs(render.HyprFileMonitorCalls(readFile(path)))
}

func (w *hyprWriter) moduleText(in Inputs, spec any) string {
	return w.module(in, spec, w.includePath())
}

func (w *hyprWriter) module(in Inputs, spec any, path string) string {
	return render.ModuleLua(jsonx.Obj(
		"header", hyprHeader, "includeLines", w.includeLines(), "requiredSettings", in.flag("requiredSettings"),
		"binds", strs(w.tables.BindLines(activeBinds(in), in.get("ctx"))),
		"look", strs(render.LookLua(getAny(spec, "look"), w.schemaOf("WindowLook"))),
		"input", strs(render.InputLua(getAny(spec, "input"), w.schemaOf("Input"))),
		"blur", strs(w.tables.BlurLua(getAny(spec, "surfaces"))),
		"layers", strs(w.tables.LayerRulesLua()),
		"monitors", w.monitorCalls(in, path),
		"strips", strs(w.stripsLua(in))))
}

func (w *hyprWriter) managedText(in Inputs, spec any) string {
	props := jsonx.NewObject()
	for _, src := range []any{w.schemaOf("Compositor", "hyprland"), w.schemaOf("WindowBehaviour")} {
		p := getAny(src, "properties")
		if o, ok := p.(*jsonx.Object); ok {
			for _, k := range o.Keys() {
				props.Set(k, o.Value(k))
			}
		}
	}
	cursor := getAny(getAny(spec, "input"), "cursor")
	return w.tables.ManagedLua(w.module(in, spec, w.dir()+"hyprland.lua"), in.get("managed"), jsonx.Obj(
		"header", hyprHeader, "userDir", w.dir()+"user", "session", in.get("session"), "env", sessionEnv(in, spec),
		"cursor", cursor, "schema", jsonx.Obj("properties", props), "resolveHex", resolveHex(in),
		"motion", in.get("motion"), "start", startOf(in)))
}

func (w *hyprWriter) emptyModuleText() string { return render.EmptyModuleLua(hyprHeader) }

func (w *hyprWriter) releasedText(in Inputs, mode string) string {
	start := w.autostartLines(in)
	if mode == "included" {
		start = w.includeLines() + "\n" + start
	}
	return render.ReleasedLua(w.dir()+"user", start)
}

func (w *hyprWriter) liveLines(in Inputs, spec any) []string {
	out := render.LookLua(getAny(spec, "look"), w.schemaOf("WindowLook"))
	out = append(out, render.InputLua(getAny(spec, "input"), w.schemaOf("Input"))...)
	return append(out, w.tables.BlurLua(getAny(spec, "surfaces"))...)
}

func (w *hyprWriter) blurLines(in Inputs, spec any) []string {
	return append(render.LookBlurLua(getAny(spec, "look")), w.tables.BlurLua(getAny(spec, "surfaces"))...)
}

func (w *hyprWriter) validate(context.Context, string) string { return "" }

func (w *hyprWriter) eval(ctx context.Context, lua string) bool {
	if lua == "" {
		return true
	}
	reply, err := w.ipc.Eval(ctx, lua)
	if err != nil {
		w.logf("Hyprland didn't take axiom's Lua: %v", err)
		return false
	}
	if reply != "" {
		w.logf("Hyprland refused axiom's Lua: %s", reply)
		return false
	}
	return true
}

// addLayerRules adds the layer rules stacking axiom's surfaces
// (render.LayerRulesLua), which a config reload drops: one eval, each
// rule in its own pcall, so one Hyprland rejects doesn't drop the rest.
// Named rules, so adding them again replaces them.
func (w *hyprWriter) addLayerRules(ctx context.Context) {
	rules := w.tables.LayerRulesLua()
	for i, rule := range rules {
		rules[i] = "pcall(function() " + rule + " end)"
	}
	w.eval(ctx, strings.Join(rules, "\n"))
}

func (w *hyprWriter) runLive(ctx context.Context, lines []string) bool {
	return w.eval(ctx, strings.Join(lines, "\n"))
}

func (w *hyprWriter) setCursor(ctx context.Context, cursor any) { w.ipc.SetCursor(ctx, cursor) }

// The keys the runtime layer bound live in Hyprland's Lua state, which a
// reload resets along with the binds and which outlives the daemon; they're
// unbound before the binds are read, so they don't look like the user's
const hyprUnbindLua = "for _, key in ipairs(AXIOM_RUNTIME_KEYS or {}) do hl.unbind(key) end\nAXIOM_RUNTIME_KEYS = nil"

func (w *hyprWriter) runtimeApply(ctx context.Context, in Inputs, live func() []string) {
	entries, animations, ok := w.runtime.read(func() (any, any, bool) {
		w.eval(ctx, hyprUnbindLua)
		binds, err := w.ipc.JSON(ctx, "binds")
		if err != nil {
			return nil, nil, false
		}
		anims, _ := w.ipc.JSON(ctx, "animations")
		return binds, anims, true
	})
	if !ok {
		w.logf("Can't read Hyprland's binds; the runtime layer waits")
		return
	}
	binds := w.runtime.plan(in, func(b any) bool { return w.complete(in, b) }, entries)
	keys := make([]string, len(binds))
	for i, b := range binds {
		keys[i] = render.LuaString(render.BindKey(getAny(b, "key")))
	}
	// The keys recorded right after the binds: a Lua error later in the
	// chunk (an hl function this version lacks) would leave them unrecorded.
	// A refused value isn't one: Hyprland reports it and runs on
	lines := append(w.tables.BindLines(jsonx.Arr(binds...), in.get("ctx")), "AXIOM_RUNTIME_KEYS = { "+strings.Join(keys, ", ")+" }")
	if in.flag("requiredSettings") {
		overridden := false
		if first, ok := getIndex(animations, 0).(*jsonx.Array); ok {
			for _, a := range first.Items {
				if jsonx.ToString(getAny(a, "name")) == "workspaces" {
					overridden = jsonx.Truthy(getAny(a, "overridden"))
					break
				}
			}
		}
		lines = append(lines, render.RequiredLua(!overridden)...)
	}
	lines = append(lines, live()...)
	lines = append(lines, render.StripsRuntimeLua(w.stripsLua(in), in.str("stripsKey"))...)
	w.eval(ctx, strings.Join(lines, "\n"))
}

func getIndex(v any, i int) any {
	if a, ok := v.(*jsonx.Array); ok && i < len(a.Items) {
		return a.Items[i]
	}
	return nil
}

func (w *hyprWriter) runtimeClear(ctx context.Context) {
	w.runtime.clear()
	w.eval(ctx, hyprUnbindLua)
}

func (w *hyprWriter) skippedKeys() []string { return w.runtime.skipped }

// checkLoaded: Hyprland answers "ok" when the file's marker is set in its
// Lua state
func (w *hyprWriter) checkLoaded(ctx context.Context, in Inputs, mode string) (bool, bool) {
	reply, err := w.ipc.Eval(ctx, "if not AXIOM_INCLUDED then error('axiom: not loaded') end")
	return err == nil && reply == "", false
}

func (w *hyprWriter) reload(ctx context.Context) { w.ipc.Request(ctx, "reload") }

func (w *hyprWriter) screenPower(ctx context.Context, on bool) error {
	action := "off"
	if on {
		action = "on"
	}
	reply, err := w.ipc.Request(ctx, `dispatch hl.dsp.dpms({ action = "`+action+`" })`)
	if err != nil {
		return err
	}
	if reply = strings.TrimSpace(reply); reply != "ok" {
		return fmt.Errorf("hyprland: dpms %s: %s", action, reply)
	}
	return nil
}

func (w *hyprWriter) reloads(ctx context.Context, out chan<- ipc.Reload) error {
	return w.ipc.Reloads(ctx, out)
}

func (w *hyprWriter) configReloaded(context.Context, Inputs) bool  { return false }
func (w *hyprWriter) ownKey(Inputs) string                         { return "" }
func (w *hyprWriter) entries(context.Context, Inputs) *jsonx.Array { return nil }
func (w *hyprWriter) runningConfig(Inputs) string                  { return "" }

func strs(list []string) *jsonx.Array {
	a := jsonx.Arr()
	for _, s := range list {
		a.Append(s)
	}
	return a
}

func (w *hyprWriter) seenReload() { w.runtime.reloads.Add(1) }

// teardownSteps: a reload takes the binds, the look and the input out, and
// the cursor is set back by hand (a runtime setcursor outlives a reload);
// partial: the layer's binds only.
func (w *hyprWriter) teardownSteps(in Inputs, partial bool) []session.Step {
	var steps []session.Step
	if partial {
		steps = append(steps, session.Step{Op: "eval", Lines: []string{hyprUnbindLua}})
	} else {
		steps = append(steps, session.Step{Op: "reload"})
	}
	if w.state.LiveCursor != "" {
		// What is in force can't be queried: Hyprland's own variables first,
		// then the session's XCursor ones
		size, _ := strconv.Atoi(cmp.Or(w.getenv("HYPRCURSOR_SIZE"), w.getenv("XCURSOR_SIZE")))
		if size <= 0 {
			size = 24
		}
		theme := cmp.Or(w.getenv("HYPRCURSOR_THEME"), w.getenv("XCURSOR_THEME"), "default")
		steps = append(steps, session.Step{Op: "setcursor", Theme: theme, Size: size})
	}
	return steps
}

// reloadStartsAxiom reads the user's hyprland.lua (or hyprland.conf) and
// the files it loads, and says whether a reload may start axiom: any line
// matching in's startPattern that isn't a comment, in the main file or any
// followed one. Parsing the config's own structure would always have holes,
// and the costs are lopsided: missing a start launches a second axiom on
// quit, an extra match only leaves the look until the next reload. So it
// takes the safe side:
//   - a user's own `hyprland.start` handler that starts axiom counts too
//     (a partial teardown), except axiom's own one-line form (autostartLines);
//   - `source =` is followed, globs too; a `source`, `require` or `dofile`
//     whose target can't be resolved (a $variable, a missing or unreadable
//     file, a Lua module outside the config folder, a computed one) counts
//     as starting axiom.
func (w *hyprWriter) reloadStartsAxiom(in Inputs) (bool, string) {
	pattern := startPatternOf(in)
	if pattern == nil {
		return false, ""
	}
	main, conf := w.dir()+"hyprland.lua", false
	if _, err := os.Stat(main); err != nil {
		main, conf = w.dir()+"hyprland.conf", true
	}
	seen := map[string]bool{}
	var scan func(path string, conf bool, depth int) (bool, string)
	scan = func(path string, conf bool, depth int) (bool, string) {
		path = filepath.Clean(path)
		if seen[path] || depth > 8 {
			return false, ""
		}
		seen[path] = true
		data, err := os.ReadFile(path)
		if err != nil {
			return true, "can't read " + path
		}
		for _, line := range strings.Split(string(data), "\n") {
			trimmed := strings.TrimSpace(line)
			if conf {
				// exec-once never runs again on a reload (hyprlang)
				if strings.HasPrefix(trimmed, "#") || hyprExecOnce.MatchString(line) {
					continue
				}
				if m := hyprSource.FindStringSubmatch(line); m != nil {
					for _, target := range w.sourceTargets(path, m[1]) {
						if target == "" {
							return true, "source = " + m[1] + " (can't be resolved)"
						}
						if ok, l := scan(target, true, depth+1); ok {
							return true, l
						}
					}
					continue
				}
			} else {
				if strings.HasPrefix(trimmed, "--") {
					continue
				}
				for _, m := range hyprRequire.FindAllStringSubmatch(line, -1) {
					target := w.luaTarget(m[2], m[1] == "require")
					if target == "" {
						if filepath.Clean(m[2]) == filepath.Clean(w.includePath()) {
							continue // axiom's own module
						}
						return true, trimmed + " (can't be resolved)"
					}
					if ok, l := scan(target, false, depth+1); ok {
						return true, l
					}
				}
				if hyprComputedLoad.MatchString(line) {
					return true, trimmed + " (can't be resolved)"
				}
				if hyprOwnStart.MatchString(line) {
					continue
				}
			}
			if pattern.MatchString(line) {
				return true, trimmed
			}
		}
		return false, ""
	}
	if ok, l := scan(main, conf, 0); ok {
		return true, l
	}
	// A managed or released config loads user/*.lua through
	// pcall(require, "user." .. name), which no literal require names
	if !conf {
		files, _ := filepath.Glob(filepath.Join(w.dir(), "user", "*.lua"))
		for _, f := range files {
			if ok, l := scan(f, false, 1); ok {
				return true, l
			}
		}
	}
	return false, ""
}

// sourceTargets are the files a conf's `source =` names, a glob expanded; a
// "" is a target that can't be resolved
func (w *hyprWriter) sourceTargets(from, name string) []string {
	name = strings.TrimSpace(name)
	if strings.Contains(name, "$") {
		return []string{""}
	}
	if rest, ok := strings.CutPrefix(name, "~/"); ok {
		name = filepath.Join(w.getenv("HOME"), rest)
	} else if !filepath.IsAbs(name) {
		name = filepath.Join(filepath.Dir(from), name)
	}
	if !strings.ContainsAny(name, "*?[") {
		return []string{name}
	}
	matches, err := filepath.Glob(name)
	if err != nil {
		return []string{""}
	}
	return matches
}

// luaTarget is the file a literal dofile/require names, under the config
// folder ("" for any other, or one that isn't there)
func (w *hyprWriter) luaTarget(name string, require bool) string {
	var candidates []string
	if require {
		rel := strings.ReplaceAll(name, ".", "/")
		candidates = []string{filepath.Join(w.dir(), rel+".lua"), filepath.Join(w.dir(), rel, "init.lua")}
	} else if filepath.IsAbs(name) {
		candidates = []string{name}
	} else {
		candidates = []string{filepath.Join(w.dir(), name)}
	}
	for _, c := range candidates {
		if rel, err := filepath.Rel(filepath.Clean(w.dir()), filepath.Clean(c)); err == nil && !strings.HasPrefix(rel, "..") {
			if _, err := os.Stat(c); err == nil {
				return c
			}
		}
	}
	return ""
}

var (
	hyprExecOnce = regexp.MustCompile(`^\s*exec-once\s*=`)
	hyprSource   = regexp.MustCompile(`^\s*source\s*=\s*(.+?)\s*$`)
	hyprRequire  = regexp.MustCompile(`\b(require|dofile)\s*\(?\s*["']([^"']+)["']`)
	// a require or dofile whose argument isn't a literal
	hyprComputedLoad = regexp.MustCompile(`\b(require|dofile)\s*\(\s*[^"'\s)]`)
	// axiom's own autostart line (hyprWriter.autostartLines)
	hyprOwnStart = regexp.MustCompile(`^\s*hl\.on\(["']hyprland\.start["'],\s*function\(\)\s*hl\.exec_cmd\(.*\)\s*end\)\s*--\s*axiom\s*$`)
)
