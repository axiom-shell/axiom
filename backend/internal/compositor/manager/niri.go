// niriWriter is niri's config writer: axiom's layer as niri's KDL
// (docs/dev/compositor/niri-backend.md). niri takes nothing at runtime: its
// files carry the look and the input (liveByFile), and the detached mode is
// a wrapper niri loads in place of the user's config (load-config-file),
// including it and then axiom's module. Binds on keys the user's own config
// binds are left out of every file, so theirs win.
type niriWriter struct {
	env
	ipc        *ipc.Niri
	mainConfig string
	// The binds the user's own config holds (BindKeys' entries), nil until
	// read
	userEntries *jsonx.Array
	runtimeOn   bool
	lastFailed  bool
	reported    map[string]bool
	skipped     []string
	// refused is niri's error for the last detached module it refused
	// (problems' Runtime), and niri the command checking it
	refused string
	niri    string
}

const niriHeader = "// Generated by axiom"

func newNiri(e env, n *ipc.Niri) *niriWriter {
	w := &niriWriter{env: e, ipc: n, reported: map[string]bool{}, niri: "niri"}
	w.readUserConfig()
	return w
}

func (w *niriWriter) header() string        { return niriHeader }
func (w *niriWriter) takeoverKind() string  { return "niri" }
func (w *niriWriter) liveByFile() bool      { return true }
func (w *niriWriter) takesBack(string) bool { return false }

func (w *niriWriter) dir() string          { return w.configHome() + "/niri/" }
func (w *niriWriter) includePath() string  { return w.stateDir + "niri.kdl" }
func (w *niriWriter) detachedPath() string { return w.stateDir + "niri-detached-module.kdl" }
func (w *niriWriter) wrapperPath() string  { return w.stateDir + "niri-detached.kdl" }
func (w *niriWriter) managedPath() string  { return w.dir() + "config.kdl" }
func (w *niriWriter) userDir() string      { return w.dir() + "user" }
func (w *niriWriter) includeLines() string { return "include " + render.KdlString(w.includePath()) }

func (w *niriWriter) startNode(in Inputs) any {
	return render.Node("spawn-sh-at-startup", jsonx.Arr(startCommand(in)), nil, nil)
}

func (w *niriWriter) files(in Inputs) files {
	autostart := render.KdlSerialize(jsonx.Arr(w.startNode(in)), 0)
	return files{
		ConfigDir: w.dir(), IncludePath: w.includePath(), ManagedPath: w.managedPath(), UserDir: w.userDir(), UserFiles: w.userDir() + "/*.kdl",
		IncludeLines: w.includeLines(), AutostartLines: autostart,
		IncludeTarget: jsonx.Obj("title", "Load axiom's module", "file", w.mainConfig, "text", w.includeLines(), "place", "end",
			"comment", "//", "accept", `^\s*include\s+.*axiom/niri\.kdl`,
			"note", "Adds the line at the end, so axiom's look wins; binds on keys your config binds stay yours."),
		AutostartTarget: jsonx.Obj("title", "Start axiom", "file", w.mainConfig, "text", autostart, "place", "end",
			"comment", "//", "accept", in.str("startPattern"),
			"note", "Adds the line at the end: niri starts axiom with every session."),
	}
}

func (w *niriWriter) problems(in Inputs) problems {
	f := w.files(in)
	p := problems{
		NotIncluded: `Compositor mode is "included", but your niri config doesn't include ` + f.IncludePath + "; add at its end:\n" + f.IncludeLines,
		NotManaged:  `Compositor mode is "managed", but ` + f.ManagedPath + " isn't loaded",
		Blocked:     `Compositor mode is "managed", but ` + f.ConfigDir + ` is a symlink or in a git repository, so axiom won't take it over; use "included" instead. Applying axiom's layer at runtime meanwhile.`,
		Failed:      "niri couldn't load its config (see niri's log, or run `niri validate`), so it still runs the one before.",
		Invalid: func(err string) string {
			return "niri refuses the config axiom made, so it wasn't written (a raw bind?):\n" + err
		},
	}
	if w.refused != "" {
		p.Runtime = p.Invalid(w.refused)
	}
	return p
}

func (w *niriWriter) monitorPattern() (*regexp.Regexp, string) {
	return regexp.MustCompile(`^[[:space:]]*output[[:space:]]`), "*.kdl"
}

func (w *niriWriter) complete(in Inputs, bind any) bool {
	return w.tables.NiriIsComplete(bind, in.get("ctx"))
}

// plan is axiom's complete binds against the user's: those to write, and
// those whose key the user's config already binds
func (w *niriWriter) plan(in Inputs) *jsonx.Object {
	var bindable []any
	for _, b := range itemsOf(activeBinds(in)) {
		if w.complete(in, b) {
			bindable = append(bindable, b)
		}
	}
	plan := render.RuntimeBinds(jsonx.Arr(bindable...), orNil(nilArr(w.userEntries), jsonx.Arr()))
	w.skipped = strList(plan.Value("skipped"))
	for _, key := range w.skipped {
		if id := render.KeyID(key); !w.reported[id] {
			w.logf("%s is bound by your niri config; leaving axiom's bind out", key)
			w.reported[id] = true
		}
	}
	return plan
}

func nilArr(a *jsonx.Array) any {
	if a == nil {
		return nil
	}
	return a
}

func (w *niriWriter) outputs(in Inputs, path string) any {
	if rules := in.get("outputRules"); rules != nil {
		return render.NiriOutputNodes(rules)
	}
	return render.NiriFileOutputNodes(readFile(path))
}

// parts are what every file holds (mode: the Compositor.mode it's for).
// With WindowSwitcher.compositorSwitcher, the switch windows keys are niri's
// own switcher's in the included and managed files; detached keeps axiom's
// (the maintainer, 2026-10-29). Managed writes niri's switcher binds even
// with none of them, empty, so niri's default keys are gone: its binds are
// exactly axiom's.
func (w *niriWriter) parts(in Inputs, spec any, path string, mode string) *jsonx.Object {
	look := render.NiriLookNodes(getAny(spec, "look"))
	look.Append(w.tables.NiriSurfaceBlurNodes(getAny(spec, "surfaces")).Items...)
	binds := w.plan(in).Value("apply")
	options := render.NiriOptionNodes(w.schemaOf("Workspaces"), in.get("stripOptions"), false)
	var recent *jsonx.Object
	if mode != "detached" && in.get("compositorSwitcher") == true {
		binds, recent = w.tables.NiriRecentWindows(binds)
	}
	if recent == nil && mode == "managed" {
		recent = render.Node("recent-windows", nil, nil, jsonx.Arr(render.Node("binds", nil, nil, jsonx.Arr())))
	}
	if recent != nil {
		options.Append(recent)
	}
	return jsonx.Obj("header", niriHeader, "includeLines", w.includeLines(),
		"binds", nilObj(w.tables.NiriBindsNode(binds, in.get("ctx"))),
		"outputs", w.outputs(in, path),
		"options", options,
		"look", look,
		"input", render.NiriInputNodes(getAny(spec, "input"), w.schemaOf("Input")))
}

func (w *niriWriter) moduleText(in Inputs, spec any) string {
	return render.NiriModuleText(w.parts(in, spec, w.includePath(), "included"))
}

// userFiles are user/*.kdl, in name order, as the managed config includes
// them (niri takes no globs)
func (w *niriWriter) userFiles() []string {
	var names []string
	entries, _ := os.ReadDir(w.userDir())
	for _, e := range entries {
		info, err := os.Stat(filepath.Join(w.userDir(), e.Name()))
		if err == nil && info.Mode().IsRegular() && strings.HasSuffix(e.Name(), ".kdl") && !strings.HasPrefix(e.Name(), ".") {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	return names
}

func (w *niriWriter) managedText(in Inputs, spec any) string {
	parts := w.parts(in, spec, w.managedPath(), "managed")
	options := render.NiriOptionNodes(w.schemaOf("WindowBehaviour"), in.get("behaviour"), false)
	options.Append(render.NiriOptionNodes(w.schemaOf("Compositor", "niri"), in.get("niriOptions"), false).Items...)
	// niri's own corner is always off: hot corners are axiom's (HotCorners)
	render.KdlSetPath(options, "gestures.hot-corners.off", jsonx.Arr(), nil)
	options.Append(itemsOf(parts.Value("options"))...)
	parts.Set("userDir", w.userDir())
	parts.Set("userFiles", strs(w.userFiles()))
	parts.Set("options", options)
	parts.Set("env", sessionEnv(in, spec))
	parts.Set("start", startOf(in))
	parts.Set("autostart", getAny(in.get("session"), "autostart"))
	parts.Set("isAgent", render.Func(func(a ...any) any { return len(a) > 0 && w.tables.IsAgentCommand(a[0]) }))
	return render.NiriManagedText(parts)
}

func (w *niriWriter) emptyModuleText() string { return render.NiriEmptyModuleText(niriHeader) }

func (w *niriWriter) releasedText(in Inputs, mode string) string {
	end := jsonx.Arr()
	if mode == "included" {
		end.Append(render.Node("include", jsonx.Arr(w.includePath()), nil, nil))
	}
	return render.NiriReleasedText(w.userDir(), strs(w.userFiles()), jsonx.Arr(w.startNode(in)), end)
}

