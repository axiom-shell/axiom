var includeLine = regexp.MustCompile(`^\s*include\s`)

// validate checks a whole file of axiom's with niri itself before it's
// written, its includes left out (they name the user's files, checked when
// niri loads them)
func (w *niriWriter) validate(ctx context.Context, text string) string {
	var own []string
	for _, l := range strings.Split(text, "\n") {
		if !includeLine.MatchString(l) {
			own = append(own, l)
		}
	}
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, w.niri, "validate", "-c", "/dev/stdin")
	cmd.Stdin = strings.NewReader(strings.Join(own, "\n"))
	out, err := cmd.CombinedOutput()
	if err == nil {
		return ""
	}
	// No niri to ask (not on the daemon's $PATH): niri itself checks the
	// file when it loads it, and keeps the config it runs if it refuses it
	if errors.Is(err, exec.ErrNotFound) {
		w.logf("Can't check axiom's niri config before writing it: %v", err)
		return ""
	}
	var lines []string
	for _, l := range strings.Split(string(out), "\n") {
		if l != "" && !strings.Contains(l, " DEBUG ") && !strings.Contains(l, " INFO ") {
			lines = append(lines, l)
		}
	}
	if msg := strings.TrimSpace(strings.Join(lines, "\n")); msg != "" {
		return msg
	}
	return "niri validate failed"
}

func (w *niriWriter) runtimeApply(ctx context.Context, in Inputs, _ func() []string) {
	w.runtimeOn = true
	if w.userEntries == nil {
		return
	}
	module := render.NiriModuleText(w.parts(in, in.get("specFile"), w.detachedPath(), "detached"))
	wrapper := render.NiriWrapperText(niriHeader, w.mainConfig, w.detachedPath())
	if w.refused = w.validate(ctx, module); w.refused != "" {
		return
	}
	for _, f := range [][2]string{{w.detachedPath(), module}, {w.wrapperPath(), wrapper}} {
		if readFile(f[0]) != f[1] {
			if err := writeFile(f[0], f[1]); err != nil {
				w.logf("Could not write %s: %v", f[0], err)
			}
		}
	}
	if !w.state.NiriWrapper {
		w.loadConfig(ctx, w.wrapperPath(), true)
	}
}

func (w *niriWriter) runtimeClear(ctx context.Context) {
	w.runtimeOn = false
	if w.state.NiriWrapper {
		w.loadConfig(ctx, w.mainConfig, false)
	}
}

// loadConfig has niri load path as its config, noting whether it's the
// wrapper
func (w *niriWriter) loadConfig(ctx context.Context, path string, wrapper bool) {
	if err := w.ipc.Action(ctx, map[string]any{"LoadConfigFile": map[string]any{"path": path}}); err != nil {
		w.logf("niri didn't load %s: %v", path, err)
		return
	}
	w.state.NiriWrapper = wrapper
	w.state.save()
}

// checkLoaded: the included module reached from the user's config, or the
// managed config being niri's (it starts with the header); failed when niri
// couldn't load its config at all
func (w *niriWriter) checkLoaded(ctx context.Context, in Inputs, mode string) (bool, bool) {
	if w.lastFailed {
		return false, true
	}
	if mode == "managed" {
		return w.mainConfig == w.managedPath() && strings.HasPrefix(readFile(w.managedPath()), niriHeader), false
	}
	r, err := userconf.ResolveNiri(w.mainConfig, nil, "", w.getenv)
	return err == nil && slices.Contains(r.Loaded, w.includePath()), false
}

// reload: niri reloads the files it loads as they change, but not a module
// it doesn't load yet
func (w *niriWriter) reload(ctx context.Context) {
	w.ipc.Action(ctx, map[string]any{"LoadConfigFile": map[string]any{"path": nil}})
}

func (w *niriWriter) screenPower(ctx context.Context, on bool) error {
	action := "PowerOffMonitors"
	if on {
		action = "PowerOnMonitors"
	}
	return w.ipc.Action(ctx, map[string]any{action: map[string]any{}})
}

func (w *niriWriter) reloads(ctx context.Context, out chan<- ipc.Reload) error {
	return w.ipc.Reloads(ctx, out)
}

// readUserConfig reads the config niri started with and the binds it holds
// (axiom's files left out: the modules, and the managed config's own nodes)
func (w *niriWriter) readUserConfig() bool {
	w.mainConfig = userconf.NiriMain(w.getenv)
	before := ""
	if w.userEntries != nil {
		before = string(jsonx.MarshalCompact(w.userEntries))
	}
	r, err := userconf.ResolveNiri(w.mainConfig, []string{w.includePath(), w.detachedPath()}, niriHeader, w.getenv)
	if err != nil || len(r.Loaded) == 0 {
		if err == nil {
			w.logf("Can't read your niri config: %s: not found", w.mainConfig)
		} else {
			w.logf("Can't read your niri config: %v", err)
		}
		// Nothing of the user's known: none skipped
		if w.userEntries == nil {
			w.userEntries = jsonx.Arr()
		}
		return false
	}
	w.userEntries = userconf.NiriBinds(r.Files, userconf.RunningNested(w.getenv))
	return string(jsonx.MarshalCompact(w.userEntries)) != before
}

func (w *niriWriter) configReloaded(context.Context, Inputs) bool { return w.readUserConfig() }

func (w *niriWriter) ownKey(in Inputs) string {
	return string(jsonx.MarshalCompact(w.plan(in))) + "|" + strings.Join(w.userFiles(), ",")
}

func (w *niriWriter) entries(ctx context.Context, in Inputs) *jsonx.Array {
	if w.userEntries == nil {
		return nil
	}
	out := jsonx.Arr(w.userEntries.Items...)
	out.Append(w.tables.NiriBindEntries(w.plan(in).Value("apply"), in.get("ctx")).Items...)
	return out
}

// runningConfig is the config niri runs now: the wrapper while it's
// loaded, else the user's (what NiriManager reads niri's gaps from)
func (w *niriWriter) runningConfig(Inputs) string {
	if w.state.NiriWrapper {
		return w.wrapperPath()
	}
	return w.mainConfig
}

