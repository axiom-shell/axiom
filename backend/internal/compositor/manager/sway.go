// swayWriter is sway's config writer: axiom's layer as sway's commands
// (docs/dev/compositor/sway-backend.md):
//
//	detached  sent at runtime; binds on keys the user's config already
//	          binds are skipped
//	included  the file at $XDG_STATE_HOME/axiom/sway.conf, which the user's
//	          sway config includes
//	managed   ~/.config/sway/config itself, including user/* after it
//
// SwayFX's part of the look only ever goes at runtime, never into a file,
// so the config still loads in plain sway.
type swayWriter struct {
	env
	ipc       *ipc.Sway
	runtime   runtimeLayer
	runtimeOn bool
	// unbindAt: the reload count state.SwayUnbinds was recorded at; a
	// reload since dropped what it takes out
	unbindAt int64
	// fresh: the daemon wasn't carried over, so the saved unbinds may name
	// keys the user's config binds now (dropTaken filters them, once)
	fresh bool
	// unread: why the user's config couldn't be read (wholly) at the last
	// try, or ""
	unread string
}

const swayHeader = "# Generated by axiom"

func newSway(e env, s *ipc.Sway) *swayWriter {
	w := &swayWriter{env: e, ipc: s, runtime: runtimeLayer{logf: e.logf, configName: "sway"}, fresh: !e.carried}
	if !e.carried {
		// The saved list may be stale: a duplicate for_window runs the same
		// idempotent commands twice, a trusted stale list could leave rules out
		e.state.SwayRules = nil
		e.state.SwayPaused = swayPaused{}
	}
	return w
}

func (w *swayWriter) header() string       { return swayHeader }
func (w *swayWriter) takeoverKind() string { return "sway" }
func (w *swayWriter) liveByFile() bool     { return false }

// SwayManager sets every window's opacity back to 1 itself
func (w *swayWriter) takesBack(part string) bool { return part == "opacity" }

func (w *swayWriter) dir() string         { return w.configHome() + "/sway/" }
func (w *swayWriter) includePath() string { return w.stateDir + "sway.conf" }
func (w *swayWriter) includeLines() string {
	return "include " + render.SwayQuote(w.includePath())
}

// userMain is the user's config sway runs (userconf.SwayMain), or the
// managed path when sway runs none of theirs (none, or the system's
// example, which only the managed path's file replaces)
func (w *swayWriter) userMain() string {
	if main := userconf.SwayMain(w.getenv); main != "" && main != "/etc/sway/config" {
		return filepath.Clean(main)
	}
	return w.dir() + "config"
}

func (w *swayWriter) files(in Inputs) files {
	managed, main := w.dir()+"config", w.userMain()
	autostart := "exec " + startCommand(in)
	elsewhere := ""
	if main != filepath.Clean(managed) {
		elsewhere = main
	}
	includeNote := "Adds the lines at the top, so your own settings after them win over axiom's."
	// An i3 migrant's sway may run i3's config, which i3 may still run too
	if strings.Contains(main, "/i3/") || strings.Contains(main, "/.i3/") {
		includeNote = "Adds the lines at the top, so your own settings after them win over axiom's. This file is in i3's folder: if i3 still runs it, i3 reports axiom's sway-only lines as errors."
	}
	return files{
		ConfigDir: w.dir(), IncludePath: w.includePath(), ManagedPath: managed, UserDir: w.dir() + "user", UserFiles: w.dir() + "user/*",
		IncludeLines: w.includeLines(), AutostartLines: autostart, RunsElsewhere: elsewhere,
		IncludeTarget: jsonx.Obj("title", "Load axiom's module", "file", main, "text", w.includeLines(), "place", "start",
			"comment", "#", "accept", `^\s*include\s+.*axiom/sway\.conf`,
			"note", includeNote),
		AutostartTarget: jsonx.Obj("title", "Start axiom", "file", main, "text", autostart, "place", "end",
			"comment", "#", "accept", in.str("startPattern"),
			"note", "Adds the line at the end: sway starts axiom with every session."),
	}
}

func (w *swayWriter) problems(in Inputs) problems {
	f := w.files(in)
	p := problems{
		NotIncluded: `Compositor mode is "included", but your sway config doesn't include ` + f.IncludePath + "; add:\n" + f.IncludeLines,
		NotManaged:  `Compositor mode is "managed", but ` + f.ManagedPath + " isn't loaded",
	}
	if w.unread != "" {
		p.Runtime = "Can't read your sway config (" + w.unread + "), so axiom's binds may cover your own keys"
	}
	return p
}

// monitorPattern: an output line setting a monitor, its name bare or quoted
// ("…" or '…'), or an `output X {` block
func (w *swayWriter) monitorPattern() (*regexp.Regexp, string) {
	return regexp.MustCompile(`^\s*output\s+("[^"]*"|'[^']*'|\S+)\s+(\{|mode|res|resolution|pos|position|scale|transform|enable|disable|power)`), "*"
}

func (w *swayWriter) complete(in Inputs, bind any) bool {
	return w.tables.SwayIsComplete(bind, in.get("ctx"))
}

// outputLines are the profile for what's connected (the shell's
// outputRules), or, until it has read the outputs, what the file says
func (w *swayWriter) outputLines(in Inputs, path string) []string {
	if rules := in.get("outputRules"); rules != nil {
		return render.SwayOutputLines(rules)
	}
	return render.SwayFileOutputLines(readFile(path))
}

func (w *swayWriter) inputLines(spec any, live bool) []string {
	return render.SwayInputLines(getAny(spec, "input"), w.schemaOf("Input"), live)
}

func (w *swayWriter) module(in Inputs, spec any, path string) string {
	return render.SwayModuleText(jsonx.Obj("header", swayHeader, "includeLines", w.includeLines(),
		"binds", strs(w.tables.SwayBindLines(activeBinds(in), in.get("ctx"), false)),
		"look", strs(render.SwayLookLines(getAny(spec, "look"), false)),
		"input", strs(w.inputLines(spec, false)),
		"outputs", strs(w.outputLines(in, path)),
		"rules", getAny(in.get("windowRules"), "file")))
}

func (w *swayWriter) moduleText(in Inputs, spec any) string {
	return w.module(in, spec, w.includePath())
}

func (w *swayWriter) managedText(in Inputs, spec any) string {
	managed := w.dir() + "config"
	options := render.SwayOptionLines(w.schemaOf("WindowBehaviour"), in.get("behaviour"))
	options = append(options, render.SwayOptionLines(w.schemaOf("Compositor", "sway"), in.get("swayOptions"))...)
	return render.SwayManagedText(w.module(in, spec, managed), jsonx.Obj(
		"header", swayHeader, "userDir", w.dir()+"user", "options", strs(options), "env", sessionEnv(in, spec),
		"start", startOf(in), "autostart", getAny(in.get("session"), "autostart"),
		"isAgent", render.Func(func(a ...any) any { return len(a) > 0 && w.tables.IsAgentCommand(a[0]) })))
}

func (w *swayWriter) emptyModuleText() string { return render.SwayEmptyModuleText(swayHeader) }

func (w *swayWriter) releasedText(in Inputs, mode string) string {
	start := "exec " + startCommand(in)
	if mode == "included" {
		start = w.includeLines() + "\n" + start
	}
	return render.SwayReleasedText(w.dir()+"user", start)
}

func (w *swayWriter) liveLines(in Inputs, spec any) []string {
	var fx []string
	if in.flag("fx") {
		fx = w.tables.SwayFxLines(getAny(spec, "look"), getAny(spec, "surfaces"))
	}
	out := render.SwayLookLines(getAny(spec, "look"), true)
	out = append(out, fx...)
	return append(out, w.inputLines(spec, true)...)
}

func (w *swayWriter) blurLines(in Inputs, spec any) []string {
	if !in.flag("fx") {
		return nil
	}
	return w.tables.SwaySurfaceBlurLines(getAny(spec, "surfaces"))
}

func (w *swayWriter) validate(context.Context, string) string { return "" }

// run runs commands as one list: true when all succeeded (criteria matching
// no window are nothing to warn about)
func (w *swayWriter) run(ctx context.Context, lines []string) bool {
	ok, _ := w.send(ctx, lines)
	return ok
}

// send is run, with the error when the list didn't reach sway
func (w *swayWriter) send(ctx context.Context, lines []string) (bool, error) {
	var kept []string
	for _, l := range lines {
		if l != "" {
			kept = append(kept, l)
		}
	}
	text := strings.Join(kept, "; ")
	if text == "" {
		return true, nil
	}
	results, err := w.ipc.Run(ctx, text)
	if err != nil {
		w.logf("sway didn't take %q: %v", clip(text), err)
		return false, err
	}
	ok := true
	for _, r := range results {
		if !r.Success && r.Error != "No matching node." {
			w.logf("%q: %s", clip(text), r.Error)
			ok = false
		}
	}
	return ok, nil
}

func clip(s string) string {
	if len(s) > 160 {
		return s[:160]
	}
	return s
}

// sendEach runs lines as one list; if sway refused one (an unknown key ends
// the list there), each again alone (binding a key again is harmless); the
// error when it didn't reach sway
func (w *swayWriter) sendEach(ctx context.Context, lines []string) error {
	ok, err := w.send(ctx, lines)
	if !ok && err == nil && len(lines) > 1 {
		for _, l := range lines {
			w.run(ctx, []string{l})
		}
	}
	return err
}

func (w *swayWriter) runLive(ctx context.Context, lines []string) bool { return w.run(ctx, lines) }

// setCursor: the live lines carry the cursor's line whenever one is set
func (w *swayWriter) setCursor(context.Context, any) {}

// userBinds are the binds the user's own sway config holds (its includes
// in, axiom's files left out), or nil
func (w *swayWriter) userBinds() *jsonx.Array {
	main := userconf.SwayMain(w.getenv)
	if main == "" {
		w.unread = "none found"
		w.logf("Can't read your sway config: none found")
		return nil
	}
	text, failed := userconf.SwayText(main, []string{w.includePath()}, swayHeader, w.getenv)
	w.unread = ""
	if len(failed) > 0 {
		w.unread = "can't open " + strings.Join(failed, ", ")
		w.logf("Can't read your sway config: %s", w.unread)
	}
	return render.SwayConfigBinds(text)
}

// pausable are the binds sway has bound: the runtime layer's while it's on
// (those on keys the user's config holds were skipped, and an unbind by key
// would hit the user's own), else the layer's complete ones
func (w *swayWriter) pausable(in Inputs) []any {
	if w.runtimeOn {
		return w.runtime.applied
	}
	var out []any
	for _, b := range itemsOf(activeBinds(in)) {
		if w.complete(in, b) {
			out = append(out, b)
		}
	}
	return out
}

func (w *swayWriter) setPaused(p swayPaused) {
	w.state.SwayPaused = p
	w.state.save()
}

// notFloating drops the floating modifier's line, which sway has no bind of
// to take out (mouse drag and resize aren't paused)
func notFloating(lines []string) []string {
	return slices.DeleteFunc(slices.Clone(lines), func(l string) bool { return strings.HasPrefix(l, "floating_modifier ") })
}

// pausePlan is what a pause of in does: the commands (the binds unbound, or
// the mode defined, entered and the kept binds bound in it) and what gives
// it back
func (w *swayWriter) pausePlan(in Inputs) (send []string, now swayPaused) {
	p := in.pause()
	byID := func(ids []string) *jsonx.Array {
		out := jsonx.Arr()
		for _, b := range w.pausable(in) {
			if slices.Contains(ids, jsonx.ToString(orNil(getAny(b, "id"), ""))) {
				out.Append(b)
			}
		}
		return out
	}
	cmdCtx := in.get("ctx")
	switch {
	case p.AllExcept:
		var kept []string
		for _, b := range byID(p.Keep).Items {
			if l := w.tables.SwayBindLine(b, cmdCtx, true); l != "" {
				kept = append(kept, l)
			}
		}
		if len(kept) > 0 {
			sum := sha256.Sum256([]byte(strings.Join(kept, "\n")))
			now.Mode = "axiom_paused_" + hex.EncodeToString(sum[:4])
			// bindsym defines the mode, as the key recorder's does
			send = append([]string{`mode "` + now.Mode + `" bindsym --no-warn Mod4+Ctrl+Mod1+Shift+F24 nop`, `mode "` + now.Mode + `"`}, kept...)
		}
	case len(p.Paused) > 0:
		binds := byID(p.Paused)
		for _, u := range w.tables.SwayUnbinds(binds, cmdCtx, nil) {
			if u.Key != "" {
				send = append(send, u.Line)
			}
		}
		now.Restore = notFloating(w.tables.SwayBindLines(binds, cmdCtx, true))
	}
	return send, now
}

// pause: the earlier pause is given back (its binds bound again, its mode
// left), then pausePlan is sent. Recorded before it's sent, as setUnbind is.
func (w *swayWriter) pause(ctx context.Context, in Inputs) bool {
	old := w.state.SwayPaused
	send, now := w.pausePlan(in)
	w.setPaused(now)
	restore := slices.Clone(old.Restore)
	if old.Mode != "" && now.Mode == "" {
		restore = append(restore, "mode default")
	}
	ok := w.sendEach(ctx, restore) == nil
	return w.sendEach(ctx, send) == nil && ok
}

// unpauseSteps give back what the last pause did
func (w *swayWriter) unpauseSteps(Inputs) []session.Step {
	lines := slices.Clone(w.state.SwayPaused.Restore)
	if w.state.SwayPaused.Mode != "" {
		lines = append(lines, "mode default")
	}
	if len(lines) == 0 {
		return nil
	}
	return []session.Step{{Op: "commands", Lines: lines}}
}

func (w *swayWriter) runtimeApply(ctx context.Context, in Inputs, live func() []string) {
	w.runtimeOn = true
	// The binds go into the mode in force: not a pause's
	if w.state.SwayPaused.Mode != "" {
		w.run(ctx, []string{"mode default"})
	}
	entries, _, ok := w.runtime.read(func() (any, any, bool) {
		b := w.userBinds()
		return b, nil, b != nil
	})
	if !ok {
		entries = jsonx.Arr()
	}
	binds := jsonx.Arr(w.runtime.plan(in, func(b any) bool { return w.complete(in, b) }, entries)...)
	w.dropTaken(entries, ok && w.unread == "")
	unbind := w.unbinds()
	next := w.tables.SwayUnbinds(binds, in.get("ctx"), entries)
	// Recorded before anything is sent, the old list too until sway took it
	w.setUnbind(append(slices.Clone(unbind), next...))
	// Sent apart, in order: sway stops a command list at an invalid command,
	// so a bind it refuses would take the look with it
	// A fresh daemon that can't tell which saved keys the user binds now
	// sends none of them and keeps the list, to filter once it can
	if !w.fresh && w.sendEach(ctx, unbindLines(unbind)) == nil {
		w.setUnbind(next)
	}
	w.sendEach(ctx, w.tables.SwayBindLines(binds, in.get("ctx"), true))
	// Window rules, apart from the binds (a refused criterion would stop
	// them): sway keeps a for_window until it reloads, so only the new ones
	if fresh := w.newRules(in); len(fresh) > 0 {
		w.state.SwayRules = append(w.state.SwayRules, fresh...)
		w.state.save()
		w.sendEach(ctx, fresh)
	}
	w.run(ctx, live())
}

// runtimeRules are the window rule lines the runtime layer sends
func runtimeRules(in Inputs) []string { return strList(getAny(in.get("windowRules"), "runtime")) }

// newRules are the runtime rule lines not sent since sway last reloaded
func (w *swayWriter) newRules(in Inputs) []string {
	var fresh []string
	for _, l := range runtimeRules(in) {
		if !slices.Contains(w.state.SwayRules, l) && !slices.Contains(fresh, l) {
			fresh = append(fresh, l)
		}
	}
	return fresh
}

// runtimeRulesGone: sway keeps a for_window until it reloads, so a line sent
// and not wanted now takes a reload to go
func (w *swayWriter) runtimeRulesGone(in Inputs) bool {
	now := runtimeRules(in)
	for _, l := range w.state.SwayRules {
		if !slices.Contains(now, l) {
			return true
		}
	}
	return false
}

func (w *swayWriter) runtimeClear(ctx context.Context) {
	w.runtimeOn = false
	w.runtime.clear()
	if w.fresh {
		if user := w.userBinds(); user != nil {
			w.dropTaken(user, w.unread == "")
		}
	}
	if w.fresh {
		// The user's binds aren't known: the saved list is kept unsent
		return
	}
	if w.sendEach(ctx, unbindLines(w.unbinds())) == nil {
		w.setUnbind(nil)
	}
}

// unbinds: the commands taking out what the runtime layer bound, none once
// sway reloaded since they were recorded (the reload dropped those binds,
// and the user's config may hold the keys now)
func (w *swayWriter) unbinds() []render.SwayUnbind {
	if w.unbindAt != w.runtime.reloads.Load() {
		return nil
	}
	return w.state.SwayUnbinds
}

func (w *swayWriter) setUnbind(list []render.SwayUnbind) {
	w.state.SwayUnbinds = list
	w.unbindAt = w.runtime.reloads.Load()
	w.state.save()
}

// unbindLines are the unbinds' commands
func unbindLines(list []render.SwayUnbind) []string {
	var out []string
	for _, u := range list {
		out = append(out, u.Line)
	}
	return out
}

// dropTaken: the first time a fresh daemon looks at the unbinds an earlier
// daemon saved, it drops those of keys the user's config binds now (entries
// are its binds; a key of a submap isn't taken, as RuntimeBinds has it) and
// takes the floating modifier's restore from it, not from the saved line.
// Unless the user's binds are wholly known (known) nothing is touched, and
// the next call tries again. A list a reload made stale is left as it is.
func (w *swayWriter) dropTaken(entries any, known bool) {
	if !w.fresh || !known {
		return
	}
	w.fresh = false
	if w.unbinds() == nil {
		return
	}
	taken := map[string]bool{}
	for _, e := range itemsOf(entries) {
		if jsonx.ToString(getAny(e, "submap")) == "" {
			taken[render.EntryID(e)] = true
		}
	}
	var kept []render.SwayUnbind
	for _, u := range w.state.SwayUnbinds {
		switch {
		case u.Key == "":
			u.Line = render.SwayFloatingRestore(entries)
		case taken[u.Key]:
			continue
		}
		kept = append(kept, u)
	}
	w.setUnbind(kept)
}

func (w *swayWriter) skippedKeys() []string { return w.runtime.skipped }

// checkLoaded: only axiom's file defines the marker mode
func (w *swayWriter) checkLoaded(ctx context.Context, in Inputs, mode string) (bool, bool) {
	modes, err := w.ipc.BindingModes(ctx)
	return err == nil && slices.Contains(modes, render.SwayLoadedMode), false
}

func (w *swayWriter) reload(ctx context.Context) { w.run(ctx, []string{"reload"}) }

func (w *swayWriter) screenPower(ctx context.Context, on bool) error {
	state := "off"
	if on {
		state = "on"
	}
	results, err := w.ipc.Run(ctx, "output * power "+state)
	if err != nil {
		return err
	}
	for _, r := range results {
		if !r.Success {
			return fmt.Errorf("sway: output power %s: %s", state, r.Error)
		}
	}
	return nil
}

func (w *swayWriter) reloads(ctx context.Context, out chan<- ipc.Reload) error {
	return w.ipc.Reloads(ctx, out)
}

// configReloaded forgets a list the reload made stale, so a re-exec of the
// daemon (its count starts over) doesn't take it for a live one
func (w *swayWriter) configReloaded(context.Context, Inputs) bool {
	// the reload dropped every runtime for_window
	if w.state.SwayRules != nil {
		w.state.SwayRules = nil
		w.state.save()
	}
	// the reload brought the file's binds back and left the pause's mode
	if p := w.state.SwayPaused; p.Mode != "" || len(p.Restore) > 0 {
		w.setPaused(swayPaused{})
	}
	if w.state.SwayUnbinds != nil && w.unbinds() == nil {
		w.setUnbind(nil)
	}
	return false
}
func (w *swayWriter) ownKey(Inputs) string        { return "" }
func (w *swayWriter) runningConfig(Inputs) string { return "" }

// entries are the user's binds and axiom's in effect: those the runtime
// layer bound, or all of them while the file is loaded
func (w *swayWriter) entries(ctx context.Context, in Inputs) *jsonx.Array {
	user := w.userBinds()
	if user == nil {
		return nil
	}
	out := jsonx.Arr()
	for _, e := range user.Items {
		if jsonx.ToString(getAny(e, "submap")) == "" {
			out.Append(e)
		}
	}
	ours := activeBinds(in)
	if w.runtimeOn {
		ours = jsonx.Arr(w.runtime.applied...)
	}
	out.Append(w.tables.SwayBindEntries(ours, in.get("ctx")).Items...)
	return out
}

func (w *swayWriter) seenReload() { w.runtime.reloads.Add(1) }

// teardownSteps: a reload takes the binds, the look and the input out; when
// the user's config starts axiom at every reload (partial), only the binds
// the layer made go, by their unbinds. Window rules sent at runtime stay
// until sway next reloads (a partial teardown can't reload).
func (w *swayWriter) teardownSteps(in Inputs, partial bool) []session.Step {
	if !partial {
		return []session.Step{{Op: "reload"}}
	}
	return []session.Step{{Op: "commands", Lines: unbindLines(w.unbinds())}}
}

var execAlways = regexp.MustCompile(`^\s*exec_always\s`)

// reloadStartsAxiom: a line of the user's config (its includes in) that
// runs at every reload (exec_always) matches in's startPattern.
func (w *swayWriter) reloadStartsAxiom(in Inputs) (bool, string) {
	pattern := startPatternOf(in)
	main := userconf.SwayMain(w.getenv)
	if pattern == nil || main == "" {
		return false, ""
	}
	text, _ := userconf.SwayText(main, []string{w.includePath()}, swayHeader, w.getenv)
	for _, line := range strings.Split(text, "\n") {
		if execAlways.MatchString(line) && pattern.MatchString(line) {
			return true, strings.TrimSpace(line)
		}
	}
	return false, ""
}
