// swayWriter is sway's config writer: axiom's layer as sway's commands
// (docs/dev/compositor/sway-backend.md):
//
//	detached  sent at runtime; binds on keys the user's config already
//	          binds are skipped
//	included  the file at $XDG_STATE_HOME/axiom/sway.conf, which the user's
//	          sway config includes
//	managed   ~/.config/sway/config itself, including user/* after it
//
// SwayFX's part of the look only ever goes at runtime, never into a file,
// so the config still loads in plain sway.
type swayWriter struct {
	env
	ipc       *ipc.Sway
	runtime   runtimeLayer
	runtimeOn bool
	// unread: the user's config couldn't be read at the last try
	unread bool
}

const swayHeader = "# Generated by axiom"

func newSway(e env, s *ipc.Sway) *swayWriter {
	return &swayWriter{env: e, ipc: s, runtime: runtimeLayer{logf: e.logf, configName: "sway"}}
}

func (w *swayWriter) header() string       { return swayHeader }
func (w *swayWriter) takeoverKind() string { return "sway" }
func (w *swayWriter) liveByFile() bool     { return false }

// SwayManager sets every window's opacity back to 1 itself
func (w *swayWriter) takesBack(part string) bool { return part == "opacity" }

func (w *swayWriter) dir() string         { return w.configHome() + "/sway/" }
func (w *swayWriter) includePath() string { return w.stateDir + "sway.conf" }
func (w *swayWriter) includeLines() string {
	return "include " + render.SwayQuote(w.includePath())
}

func (w *swayWriter) files(in Inputs) files {
	managed := w.dir() + "config"
	autostart := "exec " + startCommand(in)
	return files{
		ConfigDir: w.dir(), IncludePath: w.includePath(), ManagedPath: managed, UserDir: w.dir() + "user", UserFiles: w.dir() + "user/*",
		IncludeLines: w.includeLines(), AutostartLines: autostart,
		IncludeTarget: jsonx.Obj("title", "Load axiom's module", "file", managed, "text", w.includeLines(), "place", "start",
			"comment", "#", "accept", `^\s*include\s+.*axiom/sway\.conf`,
			"note", "Adds the lines at the top, so your own settings after them win over axiom's."),
		AutostartTarget: jsonx.Obj("title", "Start axiom", "file", managed, "text", autostart, "place", "end",
			"comment", "#", "accept", in.str("startPattern"),
			"note", "Adds the line at the end: sway starts axiom with every session."),
	}
}

func (w *swayWriter) problems(in Inputs) problems {
	f := w.files(in)
	p := problems{
		NotIncluded: `Compositor mode is "included", but your sway config doesn't include ` + f.IncludePath + "; add:\n" + f.IncludeLines,
		NotManaged:  `Compositor mode is "managed", but ` + f.ManagedPath + " isn't loaded",
		Blocked:     `Compositor mode is "managed", but ` + f.ConfigDir + ` is a symlink or in a git repository, so axiom won't take it over; use "included" instead. Applying axiom's layer at runtime meanwhile.`,
	}
	if w.unread {
		p.UnreadBinds = "Can't read your sway config (none found), so axiom's binds may cover your own keys"
	}
	return p
}

func (w *swayWriter) monitorPattern() (*regexp.Regexp, string) {
	return regexp.MustCompile(`^[[:space:]]*output[[:space:]]+[^[:space:]]+[[:space:]]+(mode|res|resolution|pos|position|scale|transform|enable|disable|power)`), "*"
}

func (w *swayWriter) complete(in Inputs, bind any) bool {
	return w.tables.SwayIsComplete(bind, in.get("ctx"))
}

// outputLines are the profile for what's connected (the shell's
// outputRules), or, until it has read the outputs, what the file says
func (w *swayWriter) outputLines(in Inputs, path string) []string {
	if rules := in.get("outputRules"); rules != nil {
		return render.SwayOutputLines(rules)
	}
	return render.SwayFileOutputLines(readFile(path))
}

func (w *swayWriter) inputLines(spec any, live bool) []string {
	return render.SwayInputLines(getAny(spec, "input"), w.schemaOf("Input"), live)
}

func (w *swayWriter) module(in Inputs, spec any, path string) string {
	return render.SwayModuleText(jsonx.Obj("header", swayHeader, "includeLines", w.includeLines(),
		"binds", strs(w.tables.SwayBindLines(activeBinds(in), in.get("ctx"), false)),
		"look", strs(render.SwayLookLines(getAny(spec, "look"), false)),
		"input", strs(w.inputLines(spec, false)),
		"outputs", strs(w.outputLines(in, path))))
}

func (w *swayWriter) moduleText(in Inputs, spec any) string {
	return w.module(in, spec, w.includePath())
}

func (w *swayWriter) managedText(in Inputs, spec any) string {
	managed := w.dir() + "config"
	options := render.SwayOptionLines(w.schemaOf("WindowBehaviour"), in.get("behaviour"))
	options = append(options, render.SwayOptionLines(w.schemaOf("Compositor", "sway"), in.get("swayOptions"))...)
	return render.SwayManagedText(w.module(in, spec, managed), jsonx.Obj(
		"header", swayHeader, "userDir", w.dir()+"user", "options", strs(options), "env", sessionEnv(in, spec),
		"start", startOf(in), "autostart", getAny(in.get("session"), "autostart"),
		"isAgent", render.Func(func(a ...any) any { return len(a) > 0 && w.tables.IsAgentCommand(a[0]) })))
}

func (w *swayWriter) emptyModuleText() string { return render.SwayEmptyModuleText(swayHeader) }

func (w *swayWriter) releasedText(in Inputs, mode string) string {
	start := "exec " + startCommand(in)
	if mode == "included" {
		start = w.includeLines() + "\n" + start
	}
	return render.SwayReleasedText(w.dir()+"user", start)
}

func (w *swayWriter) liveLines(in Inputs, spec any) []string {
	var fx []string
	if in.flag("fx") {
		fx = w.tables.SwayFxLines(getAny(spec, "look"), getAny(spec, "surfaces"))
	}
	out := render.SwayLookLines(getAny(spec, "look"), true)
	out = append(out, fx...)
	return append(out, w.inputLines(spec, true)...)
}

func (w *swayWriter) validate(context.Context, string) string { return "" }

// run runs commands as one list: true when all succeeded (criteria matching
// no window are nothing to warn about)
func (w *swayWriter) run(ctx context.Context, lines []string) bool {
	var kept []string
	for _, l := range lines {
		if l != "" {
			kept = append(kept, l)
		}
	}
	text := strings.Join(kept, "; ")
	if text == "" {
		return true
	}
	results, err := w.ipc.Run(ctx, text)
	if err != nil {
		w.logf("sway didn't take %q: %v", clip(text), err)
		return false
	}
	ok := true
	for _, r := range results {
		if !r.Success && r.Error != "No matching node." {
			w.logf("%q: %s", clip(text), r.Error)
			ok = false
		}
	}
	return ok
}

func clip(s string) string {
	if len(s) > 160 {
		return s[:160]
	}
	return s
}

// sendEach runs lines as one list; if sway refused one (an unknown key ends
// the list there), each again alone (binding a key again is harmless)
func (w *swayWriter) sendEach(ctx context.Context, lines []string) {
	if !w.run(ctx, lines) && len(lines) > 1 {
		for _, l := range lines {
			w.run(ctx, []string{l})
		}
	}
}

func (w *swayWriter) runLive(ctx context.Context, lines []string) bool { return w.run(ctx, lines) }

func (w *swayWriter) setCursor(ctx context.Context, cursor any) {
	w.run(ctx, []string{render.SwayCursorLine(getAny(cursor, "xcursor"), getAny(cursor, "size"))})
}

// userBinds are the binds the user's own sway config holds (its includes
// in, axiom's files left out), or nil
func (w *swayWriter) userBinds() *jsonx.Array {
	main := userconf.SwayMain(w.getenv)
	w.unread = main == ""
	if main == "" {
		w.logf("Can't read your sway config: none found")
		return nil
	}
	return render.SwayConfigBinds(userconf.SwayText(main, []string{w.includePath()}, swayHeader, w.getenv))
}

func (w *swayWriter) runtimeApply(ctx context.Context, in Inputs, live func() []string) {
	w.runtimeOn = true
	entries, _, ok := w.runtime.read(func() (any, any, bool) {
		b := w.userBinds()
		return b, nil, b != nil
	})
	if !ok {
		entries = jsonx.Arr()
	}
	binds := jsonx.Arr(w.runtime.plan(in, func(b any) bool { return w.complete(in, b) }, entries)...)
	unbind := w.state.SwayUnbind
	w.state.SwayUnbind = w.tables.SwayUnbindLines(binds, in.get("ctx"), entries)
	w.state.save()
	// Sent apart, in order: sway stops a command list at an invalid command,
	// so a bind it refuses would take the look with it
	w.sendEach(ctx, unbind)
	w.sendEach(ctx, w.tables.SwayBindLines(binds, in.get("ctx"), true))
	w.run(ctx, live())
}

func (w *swayWriter) runtimeClear(ctx context.Context) {
	w.runtimeOn = false
	w.runtime.clear()
	unbind := w.state.SwayUnbind
	w.state.SwayUnbind = nil
	w.state.save()
	w.sendEach(ctx, unbind)
}

func (w *swayWriter) noteReload() {
	w.runtime.noteReload()
	w.state.SwayUnbind = nil
	w.state.save()
}

func (w *swayWriter) skippedKeys() []string { return w.runtime.skipped }

// checkLoaded: only axiom's file defines the marker mode
func (w *swayWriter) checkLoaded(ctx context.Context, in Inputs, mode string) (bool, bool) {
	modes, err := w.ipc.BindingModes(ctx)
	return err == nil && slices.Contains(modes, render.SwayLoadedMode), false
}

func (w *swayWriter) reload(ctx context.Context) { w.run(ctx, []string{"reload"}) }

func (w *swayWriter) screenPower(ctx context.Context, on bool) error {
	state := "off"
	if on {
		state = "on"
	}
	results, err := w.ipc.Run(ctx, "output * power "+state)
	if err != nil {
		return err
	}
	for _, r := range results {
		if !r.Success {
			return fmt.Errorf("sway: output power %s: %s", state, r.Error)
		}
	}
	return nil
}

func (w *swayWriter) reloads(ctx context.Context, out chan<- ipc.Reload) error {
	return w.ipc.Reloads(ctx, out)
}

func (w *swayWriter) configReloaded(context.Context, Inputs) bool { return false }
func (w *swayWriter) ownKey(Inputs) string                        { return "" }
func (w *swayWriter) runningConfig(Inputs) string                 { return "" }
func (w *swayWriter) userBindsRead() bool                         { return true }

// entries are the user's binds and axiom's in effect: those the runtime
// layer bound, or all of them while the file is loaded
func (w *swayWriter) entries(ctx context.Context, in Inputs) *jsonx.Array {
	user := w.userBinds()
	if user == nil {
		return nil
	}
	out := jsonx.Arr()
	for _, e := range user.Items {
		if jsonx.ToString(getAny(e, "submap")) == "" {
			out.Append(e)
		}
	}
	ours := activeBinds(in)
	if w.runtimeOn {
		ours = jsonx.Arr(w.runtime.applied...)
	}
	out.Append(w.tables.SwayBindEntries(ours, in.get("ctx")).Items...)
	return out
}

func (w *swayWriter) seenReload() { w.runtime.reloads.Add(1) }
