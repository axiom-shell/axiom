package takeover

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// Kind is what differs between compositors in a takeover: the file, what
// counts as their example config, the lines that start axiom, and how a
// restored config is seen to load user/.
type Kind struct {
	Name string // "hyprland", "sway", "niri"
	File string // the config in its dir ("hyprland.lua")
	Ext  string // of the adopted copies in user/ (".lua")

	// The example config: $exampleEnv, else exampleDefault(getenv)
	exampleEnv     string
	exampleDefault func(getenv func(string) string) string

	// Lines left out before comparing with the example, and with the file
	// release writes
	stockSkip, releasedSkip *regexp.Regexp
	// A line already commented out, left as it is in an adopted copy
	comment *regexp.Regexp
	// A line that starts axiom or loads its module, commented out with
	// marker in an adopted copy
	axiomLine *regexp.Regexp
	marker    string
	// absInclude makes a relative include absolute from dir (nil: none)
	absInclude func(line, dir string) string
	// parses: the adopted copy's edits are only kept while it still parses
	// (and only undone on release while that parses)
	parses bool
	// left counts user/'s files a restored config doesn't load
	left func(text, userDir string) int
	// record: claim notes what it set aside in .axiom-claimed, so release
	// gives back that and not an older claim's dated backup
	record bool
}

// KindNamed is the kind called name.
func KindNamed(name string) (*Kind, bool) {
	for _, k := range []*Kind{hyprland, sway, niri} {
		if k.Name == name {
			return k, true
		}
	}
	return nil, false
}

const marker = "(axiom starts and loads itself now) "

var hyprland = &Kind{
	Name:       "hyprland",
	File:       "hyprland.lua",
	Ext:        ".lua",
	exampleEnv: "AXIOM_HYPR_EXAMPLE",
	// The first data dir's hypr/hyprland.lua (NixOS has nothing in
	// /usr/share), or "" with none
	exampleDefault: func(getenv func(string) string) string {
		dirs := getenv("XDG_DATA_DIRS")
		if dirs == "" {
			dirs = "/usr/local/share:/usr/share"
		}
		for _, data := range filepath.SplitList(dirs) {
			path := filepath.Join(data, "hypr", "hyprland.lua")
			if filepath.IsAbs(data) && isFile(path) {
				return path
			}
		}
		return ""
	},
	// The line that starts axiom (install.sh's, marked "-- axiom"). A config
	// Hyprland generated itself (with no hyprland.lua at its first start) is
	// the example too: it adds a banner and an `autogenerated` line, and
	// picks the `menu` launcher by what's installed
	stockSkip: regexp.MustCompile(`axiom.* run.*-- axiom[[:space:]]*$|^-- (-- )+--[[:space:]]*$|^-- AUTOGENERATED HYPRLAND CONFIG\.|^-- EDIT THIS CONFIG ACCORDING TO THE WIKI|^hl\.config\(\{ *autogenerated *= *true *\}\)|^local menu +=`),
	// The lines that load the included module (release writes them for that
	// mode)
	releasedSkip: regexp.MustCompile(`pcall\(dofile, .*axiom/hyprland\.lua|^if ok then axiom\.setup\(\) end`),
	comment:      regexp.MustCompile(`^[[:space:]]*--`),
	// Any `axiom run` (install.sh's, the Hyprland page's; not a bind calling
	// its IPC, which the bind merge reads) or loading its included module
	axiomLine: regexp.MustCompile(`(^|[[:space:]"'/])axiom["']?[[:space:]]+run([[:space:]"')]|$)|dofile.*axiom/hyprland\.lua|axiom\.setup\(`),
	marker:    "-- " + marker,
	parses:    true,
	// None when it loads them itself (a file release once wrote)
	left: func(text, userDir string) int {
		if strings.Contains(text, `pcall(require, "user.`) {
			return 0
		}
		return countEntries(userDir, func(e os.DirEntry) bool { return strings.HasSuffix(e.Name(), ".lua") })
	},
	record: true,
}

// sway's lines starting axiom: an `exec`/`exec_always` of `axiom run`, not an
// IPC call (a bind calling axiom stays for the bind merge), or including its
// module
var swayAxiomLine = `^[[:space:]]*(exec(_always)?[[:space:]]+([^#]*[[:space:]])?["']?([^[:space:]#"']*/)?axiom["']?[[:space:]]+run([[:space:]]+-[^[:space:]]+)*[[:space:]]*$|include .*axiom/sway\.conf)`

var sway = &Kind{
	Name:           "sway",
	File:           "config",
	Ext:            ".conf",
	exampleEnv:     "AXIOM_SWAY_EXAMPLE",
	exampleDefault: func(func(string) string) string { return "/etc/sway/config" },
	stockSkip:      regexp.MustCompile(`^[[:space:]]*(#|$)|` + swayAxiomLine),
	releasedSkip:   regexp.MustCompile(`include .*axiom/sway\.conf`),
	comment:        regexp.MustCompile(`^[[:space:]]*#`),
	axiomLine:      regexp.MustCompile(swayAxiomLine),
	marker:         "# " + marker,
	absInclude:     swayInclude,
	left: func(text, userDir string) int {
		if regexp.MustCompile(`(?m)^[[:space:]]*include .*/user/\*`).MatchString(text) {
			return 0
		}
		return countEntries(userDir, func(e os.DirEntry) bool { return e.Type().IsRegular() })
	},
	record: true,
}

// niri's nodes starting axiom: a spawn-at-startup or spawn-sh-at-startup of
// `axiom run`, flags after it at most (so not an IPC call), or including its
// module. Between two words: a space in a spawn-sh-at-startup's string, `" "`
// between spawn-at-startup's arguments
const niriSep = `("[[:space:]]+"|[[:space:]]+)`

var niriAxiomLine = `^[[:space:]]*(spawn(-sh)?-at-startup[[:space:]]+"([^"]*[[:space:]])?'?([^[:space:]"']*/)?axiom'?` + niriSep +
	`run(` + niriSep + `-[^[:space:]"]+)*"[[:space:]]*(;.*)?$|include[[:space:]].*axiom/niri(-detached)?\.kdl)`

var niri = &Kind{
	Name:           "niri",
	File:           "config.kdl",
	Ext:            ".kdl",
	exampleEnv:     "AXIOM_NIRI_EXAMPLE",
	exampleDefault: func(func(string) string) string { return "/usr/share/doc/niri/default-config.kdl" },
	stockSkip:      regexp.MustCompile(`^[[:space:]]*(//|$)|` + niriAxiomLine),
	releasedSkip:   regexp.MustCompile(`include .*axiom/niri\.kdl`),
	comment:        regexp.MustCompile(`^[[:space:]]*//`),
	axiomLine:      regexp.MustCompile(niriAxiomLine),
	marker:         "/* " + strings.TrimSuffix(marker, " ") + " */ /-",
	absInclude:     replacer(regexp.MustCompile(`^([[:space:]]*include[[:space:]][^"]*")([^/"~$][^"]*")`)),
	// niri takes no globs: each file is included by name
	left: func(text, userDir string) int {
		n := 0
		for _, e := range entries(userDir) {
			if !e.Type().IsRegular() || !strings.HasSuffix(e.Name(), ".kdl") {
				continue
			}
			included := regexp.MustCompile(`(?m)^[[:space:]]*include[[:space:]].*/user/` + regexp.QuoteMeta(e.Name()) + `"`)
			if !included.MatchString(text) {
				n++
			}
		}
		return n
	},
	record: true,
}

// replacer puts dir/ between a line's two groups where re matches
func replacer(re *regexp.Regexp) func(line, dir string) string {
	return func(line, dir string) string {
		m := re.FindStringSubmatchIndex(line)
		if m == nil {
			return line
		}
		return line[:m[3]] + dir + "/" + line[m[4]:]
	}
}

var (
	swayIncludeLine = regexp.MustCompile(`^([[:space:]]*include[[:space:]]+)(.*)$`)
	swayIncludePath = regexp.MustCompile(`"[^"]*"|'[^']*'|[^[:space:]"']+`)
)

// swayInclude makes each relative path of a sway include absolute from dir:
// sway joins its arguments and expands them as a shell would, so an include
// takes several paths, each quoted or not
func swayInclude(line, dir string) string {
	m := swayIncludeLine.FindStringSubmatch(line)
	if m == nil {
		return line
	}
	return m[1] + swayIncludePath.ReplaceAllStringFunc(m[2], func(path string) string {
		quote := ""
		if path[0] == '"' || path[0] == '\'' {
			quote = path[:1]
		}
		inner := strings.Trim(path, quote)
		if inner == "" || strings.ContainsRune("/~$", rune(inner[0])) {
			return path
		}
		return quote + dir + "/" + inner + quote
	})
}

func entries(dir string) []os.DirEntry {
	list, _ := os.ReadDir(dir)
	return list
}

func countEntries(dir string, keep func(os.DirEntry) bool) int {
	n := 0
	for _, e := range entries(dir) {
		if keep(e) {
			n++
		}
	}
	return n
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}
