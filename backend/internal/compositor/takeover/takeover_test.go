func TestStockIsOnlyBackedUp(t *testing.T) {
	t.Parallel()
	cases := map[string][2]string{
		// The example, and the user's config: give or take whitespace, blank
		// lines, comments (sway, niri) and a line starting axiom
		"hyprland": {"-- example\nhl.bind(\"SUPER + M\", hl.dsp.exit())\n",
			"-- example  \n\nhl.bind(\"SUPER + M\", hl.dsp.exit())\n" +
				`hl.on("hyprland.start", function() hl.exec_cmd("'/usr/bin/axiom' run") end) -- axiom` + "\n"},
		"sway": {"# sway's\nset $mod Mod4\nbindsym $mod+Return exec foot\n",
			"set $mod Mod4\n\n# mine now\nbindsym $mod+Return exec foot\nexec axiom run\n"},
		"niri": {"// niri's\nbinds {\n    Mod+T { spawn \"alacritty\"; }\n}\n",
			"binds {\n\n    // mine now\n    Mod+T { spawn \"alacritty\"; }\n}\nspawn-at-startup \"/opt/axiom/axiom\" \"run\"\n"},
	}
	for kind, c := range cases {
		t.Run(kind, func(t *testing.T) {
			t.Parallel()
			f := newFx(t, kind)
			f.example(c[0])
			f.write(f.kind.File, c[1])
			eq(t, f.run("check"), "stock")
			eq(t, f.run("claim"), "replaced")
			eq(t, len(listing(t, f.path("user"))), 0)
			eq(t, len(f.backups()), 1)
			// Again before the managed write: no second backup
			eq(t, f.run("claim"), "replaced")
			eq(t, len(f.backups()), 1)
			// And release gives it back
			backup := filepath.Base(f.backups()[0])
			f.ours()
			eq(t, f.run("release"), "restored:"+backup+":0")
			eq(t, f.read(f.kind.File), c[1])
			eq(t, len(f.backups()), 0)
		})
	}
}

func TestBlocked(t *testing.T) {
	t.Parallel()
	for _, kind := range kinds {
		t.Run(kind+"/symlinked dir", func(t *testing.T) {
			t.Parallel()
			f := newFx(t, kind)
			link := filepath.Join(f.tmp, "linked")
			os.Symlink(f.dir, link)
			eq(t, f.run("check", link), "blocked:link")
			eq(t, f.run("claim", link), "blocked:link")
			eq(t, len(listing(t, f.dir)), 0)
		})
		t.Run(kind+"/symlinked file", func(t *testing.T) {
			t.Parallel()
			f := newFx(t, kind)
			real := filepath.Join(f.tmp, "real")
			os.WriteFile(real, []byte("mine\n"), 0o644)
			os.Symlink(real, f.path(f.kind.File))
			eq(t, f.run("claim"), "blocked:link")
			eq(t, isLink(f.path(f.kind.File)), true)
			eq(t, exists(f.path("user")), false)
		})
		t.Run(kind+"/release never writes through a symlink", func(t *testing.T) {
			t.Parallel()
			f := newFx(t, kind)
			real := filepath.Join(f.tmp, "real")
			os.WriteFile(real, []byte(headers[kind][0]+"\n"), 0o644)
			os.Symlink(real, f.path(f.kind.File))
			eq(t, f.run("release"), "blocked:link")
			data, _ := os.ReadFile(real)
			eq(t, string(data), headers[kind][0]+"\n")
		})
	}
}

func TestGitTrackedDirIsBlocked(t *testing.T) {
	t.Parallel()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	git := func(t *testing.T, dir string) {
		cmd := exec.Command("git", "init", "-q", dir)
		cmd.Env = append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git init: %v %s", err, out)
		}
	}
	for _, kind := range kinds {
		t.Run(kind, func(t *testing.T) {
			t.Parallel()
			f := newFx(t, kind)
			f.write(f.kind.File, "mine\n")
			git(t, f.dir)
			resolved, _ := filepath.EvalSymlinks(f.dir)
			eq(t, f.run("check"), "blocked:git:"+resolved)
			eq(t, f.run("claim"), "blocked:git:"+resolved)
			eq(t, f.read(f.kind.File), "mine\n")
			eq(t, exists(f.path("user")), false)
		})
	}
	t.Run("a dir inside a repo", func(t *testing.T) {
		t.Parallel()
		f := newFx(t, "hyprland")
		repo := filepath.Join(f.tmp, "dotfiles")
		os.MkdirAll(filepath.Join(repo, "hypr"), 0o755)
		git(t, repo)
		resolved, _ := filepath.EvalSymlinks(repo)
		eq(t, f.run("claim", filepath.Join(repo, "hypr")), "blocked:git:"+resolved)
		eq(t, len(listing(t, filepath.Join(repo, "hypr"))), 0)
	})
}

