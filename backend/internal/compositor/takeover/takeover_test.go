// A config given back unchanged is the newest backup's bytes again, and
// user/ may hold an older claim's dated copy: claiming it again copies it
// anew, never resuming with that older copy
func TestHyprlandClaimAfterAReleaseCopiesTheConfigAnew(t *testing.T) {
	t.Parallel()
	f := newFx(t, "hyprland")
	f.write("user/00-previous-20250101-000000.lua", "-- an old claim's\n")
	f.write("hyprland.lua", "-- mine\n")
	eq(t, f.run("claim"), "adopted:00-previous.lua")
	f.ours()
	eq(t, f.run("release"), "restored:user/00-previous.lua:1")
	eq(t, f.read("hyprland.lua"), "-- mine\n")
	got := f.run("claim")
	if got == "adopted:00-previous-20250101-000000.lua" {
		t.Fatal("resumed with an older claim's copy")
	}
	eq(t, got, "adopted:00-previous.lua")
	eq(t, f.read("user/00-previous.lua"), "-- mine\n")
}

// Every verb holds the config dir's lock: one waits while another process
// (the daemon, a command line) changes the dir, unless its caller holds it
func TestVerbsWaitForTheDirsLock(t *testing.T) {
	t.Parallel()
	f := newFx(t, "hyprland")
	f.write("hyprland.lua", "-- mine\n")
	held, err := edit.LockDir(context.Background(), f.dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, verb := range []func(context.Context, Options) (string, error){Check, Claim, Release} {
		ctx, cancel := context.WithTimeout(context.Background(), 150*time.Millisecond)
		_, err := verb(ctx, f.options(f.dir))
		cancel()
		var ae *axerr.Error
		if !errors.As(err, &ae) || ae.Kind != axerr.Running {
			t.Fatalf("not refused while locked: %v", err)
		}
	}
	eq(t, f.read("hyprland.lua"), "-- mine\n")
	o := f.options(f.dir)
	o.Locked = true
	got, err := Claim(context.Background(), o)
	if err != nil || got != "adopted:00-previous.lua" {
		t.Fatalf("the holder's own claim: %q %v", got, err)
	}
	held.Release()
	eq(t, f.run("check"), "adopt")
}

func TestSwayIncludeMakesEveryRelativePathAbsolute(t *testing.T) {
	t.Parallel()
	for _, c := range [][2]string{
		{"include conf.d/*", "include /d/conf.d/*"},
		{`  include "my conf/a" 'b' c`, `  include "/d/my conf/a" '/d/b' /d/c`},
		{`include /etc/sway/config.d/* ~/x $HOME/y "/z" rel`, `include /etc/sway/config.d/* ~/x $HOME/y "/z" /d/rel`},
		{"included a", "included a"},
		{`include ""`, `include ""`},
	} {
		eq(t, swayInclude(c[0], "/d"), c[1])
	}
}
