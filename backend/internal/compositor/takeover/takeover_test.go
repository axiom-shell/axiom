func TestNiriAdoptAndRelease(t *testing.T) {
	t.Parallel()
	f := newFx(t, "niri")
	mine := "include \"extra.kdl\"\nspawn-sh-at-startup \"'/opt/axiom/axiom' run\"\n" +
		"spawn-at-startup \"/opt/axiom/axiom\" \"ipc\" \"bar\" \"toggle\"\n" +
		"include \"/home/u/.local/state/axiom/niri.kdl\"\nbinds {\n    Mod+Q { close-window; }\n}\n"
	f.write("config.kdl", mine)
	eq(t, f.run("check"), "adopt")
	eq(t, f.run("claim"), "adopted:00-previous.kdl")
	adopted := lines(f.read("user/00-previous.kdl"))
	eq(t, adopted[0], `include "`+f.dir+`/extra.kdl"`)
	eq(t, strings.HasPrefix(adopted[1], "/* (axiom starts and loads itself now) */ /-spawn-sh-at-startup"), true)
	// An IPC call isn't axiom starting
	eq(t, adopted[2], lines(mine)[2])
	eq(t, strings.HasPrefix(adopted[3], "/* (axiom starts and loads itself now) */ /-include"), true)
	if _, err := exec.LookPath("niri"); err == nil {
		cmd := exec.Command("niri", "validate", "-c", "/dev/stdin")
		cmd.Stdin = strings.NewReader(strings.Join(adopted[1:], "\n"))
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("niri validate: %v %s", err, out)
		}
	}
	eq(t, f.read("config.kdl"), mine)
	first := f.read("user/00-previous.kdl")
	eq(t, f.run("claim"), "adopted:00-previous.kdl")
	eq(t, len(f.backups()), 1)
	eq(t, f.read("user/00-previous.kdl"), first)
	f.ours()
	eq(t, f.run("release"), "restored:user/00-previous.kdl:0")
	// As it was, its relative include left absolute (the same file)
	eq(t, f.read("config.kdl"), strings.Replace(mine, `"extra.kdl"`, `"`+f.dir+`/extra.kdl"`, 1))
}

