// fx is one scratch config dir of a kind, with its example stubbed
type fx struct {
	t        *testing.T
	tmp, dir string
	kind     *Kind
	env      map[string]string
	clock    time.Time
	lua      luacheck.Checker
}

var headers = map[string][2]string{
	"hyprland": {"-- Generated by axiom", "-- Given back by axiom"},
	"sway":     {"# Generated by axiom", "# Given back by axiom\ninclude /x/user/*"},
	"niri":     {"// Generated by axiom", "// Given back by axiom\nspawn-sh-at-startup \"/opt/axiom/axiom run\""},
}

func newFx(t *testing.T, kind string) *fx {
	t.Helper()
	k, ok := KindNamed(kind)
	if !ok {
		t.Fatalf("no kind %s", kind)
	}
	tmp := t.TempDir()
	f := &fx{t: t, tmp: tmp, dir: filepath.Join(tmp, kind), kind: k,
		env:   map[string]string{"XDG_DATA_DIRS": filepath.Join(tmp, "nodata")},
		clock: time.Date(2026, 10, 24, 12, 0, 0, 0, time.UTC)}
	if err := os.Mkdir(f.dir, 0o755); err != nil {
		t.Fatal(err)
	}
	return f
}

func (f *fx) options(dir string) Options {
	h := headers[f.kind.Name]
	return Options{Kind: f.kind, Dir: dir, Header: h[0], Fallback: h[1],
		Getenv: func(k string) string { return f.env[k] },
		// A second apart, so each dated name is new
		Now: func() time.Time { f.clock = f.clock.Add(time.Second); return f.clock },
		Lua: f.lua}
}

func (f *fx) run(verb string, dir ...string) string {
	f.t.Helper()
	d := f.dir + "/"
	if len(dir) > 0 {
		d = dir[0]
	}
	fn := map[string]func(context.Context, Options) (string, error){"check": Check, "claim": Claim, "release": Release}[verb]
	out, err := fn(context.Background(), f.options(d))
	if err != nil {
		f.t.Fatalf("%s: %v", verb, err)
	}
	return out
}

func (f *fx) path(parts ...string) string { return filepath.Join(append([]string{f.dir}, parts...)...) }

func (f *fx) write(name, text string) {
	f.t.Helper()
	path := f.path(name)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		f.t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		f.t.Fatal(err)
	}
}

func (f *fx) read(name string) string {
	f.t.Helper()
	data, err := os.ReadFile(f.path(name))
	if err != nil {
		f.t.Fatal(err)
	}
	return string(data)
}

func (f *fx) example(text string) {
	f.t.Helper()
	path := filepath.Join(f.tmp, "example")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		f.t.Fatal(err)
	}
	f.env[f.kind.exampleEnv] = path
}

// ours writes a config axiom wrote
func (f *fx) ours() { f.write(f.kind.File, headers[f.kind.Name][0]+" (managed)\n") }

// listing is dir's paths, relative, sorted
func listing(t *testing.T, dir string) []string {
	t.Helper()
	var out []string
	filepath.WalkDir(dir, func(p string, d os.DirEntry, err error) error {
		if err == nil && p != dir {
			rel, _ := filepath.Rel(dir, p)
			out = append(out, rel)
		}
		return nil
	})
	slices.Sort(out)
	return out
}

func (f *fx) backups() []string {
	matches, _ := filepath.Glob(f.path(f.kind.File + ".axiom-backup-*"))
	return matches
}

func eq[T comparable](t *testing.T, got, want T) {
	t.Helper()
	if got != want {
		t.Fatalf("got %v, want %v", got, want)
	}
}

func lines(text string) []string { return strings.Split(strings.TrimSuffix(text, "\n"), "\n") }

