func TestSwayMain(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	vars := map[string]string{"HOME": dir, "XDG_CONFIG_HOME": filepath.Join(dir, "conf")}
	if _, err := os.Stat("/etc/sway/config"); err != nil {
		eq(t, SwayMain(env(vars)), "")
	}
	write(t, filepath.Join(dir, "conf", "sway", "config"), "")
	eq(t, SwayMain(env(vars)), filepath.Join(dir, "conf", "sway", "config"))
	write(t, filepath.Join(dir, ".sway", "config"), "")
	eq(t, SwayMain(env(vars)), filepath.Join(dir, ".sway", "config"))
}

func TestShellSplit(t *testing.T) {
	t.Parallel()
	words, err := shellSplit(`a "b c" 'd "e"' f\ g "h\"i\j" ''`)
	if err != nil {
		t.Fatal(err)
	}
	eq(t, strings.Join(words, "|"), `a|b c|d "e"|f g|h"i\j|`)
	if _, err := shellSplit(`"open`); err == nil {
		t.Fatal("an open quote split")
	}
}

