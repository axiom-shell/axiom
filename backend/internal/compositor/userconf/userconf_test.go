func write(t *testing.T, path, text string) {
	t.Helper()
	os.MkdirAll(filepath.Dir(path), 0o755)
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
}

func env(vars map[string]string) func(string) string {
	return func(k string) string { return vars[k] }
}

func bindLines(text string) []string {
	var out []string
	for _, line := range strings.Split(text, "\n") {
		if strings.HasPrefix(line, "bindsym") {
			out = append(out, line)
		}
	}
	return out
}

func eq(t *testing.T, got, want string) {
	t.Helper()
	if got != want {
		t.Fatalf("got %s\nwant %s", got, want)
	}
}

func js(v any) string { return string(jsonx.MarshalCompact(v)) }

// --- sway ---

func TestSwayIncludes(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "conf.d", "10-a.conf"), "bindsym $mod+a exec a\n")
	write(t, filepath.Join(dir, "conf.d", "20-b.conf"), "bindsym $mod+b exec b\ninclude ../config\n")
	write(t, filepath.Join(dir, "conf.d", ".hidden.conf"), "bindsym $mod+h exec h\n")
	write(t, filepath.Join(dir, "axiom.conf"), "bindsym $mod+x exec axiom\n")
	write(t, filepath.Join(dir, "config"),
		"set $dir conf.d\nset $mod Mod4\ninclude $dir/*.conf\ninclude axiom.conf\ninclude missing.conf\nbindsym $mod+c exec c\n")
	text, unread := SwayText(filepath.Join(dir, "config"), []string{filepath.Join(dir, "axiom.conf")}, "", env(nil))
	eq(t, strings.Join(unread, "|"), "")
	// Each file once (the include back to config is a loop); axiom's and a
	// hidden one left out
	eq(t, strings.Join(bindLines(text), "|"), "bindsym $mod+a exec a|bindsym $mod+b exec b|bindsym $mod+c exec c")
}

func TestSwayIncludesAsWordexpReadsThem(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "a.conf"), "bindsym $mod+a exec a\n")
	write(t, filepath.Join(dir, "b.conf"), "bindsym $mod+b exec b\n")
	write(t, filepath.Join(dir, "c d.conf"), "bindsym $mod+c exec c\n")
	write(t, filepath.Join(dir, "config"), "include b.conf a.conf\ninclude $AXIOM_TEST_DIR/a.conf\ninclude 'c d.conf'\n")
	text, _ := SwayText(filepath.Join(dir, "config"), nil, "", env(map[string]string{"AXIOM_TEST_DIR": dir}))
	eq(t, strings.Join(bindLines(text), "|"), "bindsym $mod+b exec b|bindsym $mod+a exec a|bindsym $mod+c exec c")
}

// A file that's there but can't be read is named, not skipped silently:
// the main config or an include
func TestSwayUnreadableFiles(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "a.conf"), "bindsym $mod+a exec a\n")
	write(t, filepath.Join(dir, "config"), "include a.conf\nbindsym $mod+c exec c\n")
	if err := os.Chmod(filepath.Join(dir, "a.conf"), 0); err != nil {
		t.Fatal(err)
	}
	if _, err := os.ReadFile(filepath.Join(dir, "a.conf")); err == nil {
		t.Skip("running as root: every file is readable")
	}
	text, unread := SwayText(filepath.Join(dir, "config"), nil, "", env(nil))
	eq(t, strings.Join(bindLines(text), "|"), "bindsym $mod+c exec c")
	eq(t, strings.Join(unread, "|"), filepath.Join(dir, "a.conf"))
	if err := os.Chmod(filepath.Join(dir, "config"), 0); err != nil {
		t.Fatal(err)
	}
	text, unread = SwayText(filepath.Join(dir, "config"), nil, "", env(nil))
	eq(t, text, "")
	eq(t, strings.Join(unread, "|"), filepath.Join(dir, "config"))
}

