func TestNiriIncludesAndBinds(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "extra.kdl"), "binds {\n    Mod+T { spawn \"b\"; }\n    Control+Win+Q { spawn \"q2\"; }\n}\n")
	write(t, filepath.Join(dir, "axiom.kdl"), "binds {\n    Mod+X { spawn \"axiom\"; }\n}\n")
	main := filepath.Join(dir, "config.kdl")
	write(t, main, "binds {\n    Mod+T { spawn \"a\"; }\n    Mod+Y { spawn \"a\"; }\n    Super+Ctrl+Q { spawn \"q1\"; }\n}\ninclude \"extra.kdl\"\n"+
		"include optional=true \"missing.kdl\"\ninclude \"axiom.kdl\"\ninclude \"config.kdl\"\n")
	r, err := ResolveNiri(main, nil, "", env(nil))
	if err != nil {
		t.Fatal(err)
	}
	eq(t, strings.Join(r.Loaded, "|"), main+"|"+filepath.Join(dir, "extra.kdl")+"|"+filepath.Join(dir, "axiom.kdl"))
	r, err = ResolveNiri(main, []string{filepath.Join(dir, "axiom.kdl")}, "", env(nil))
	if err != nil {
		t.Fatal(err)
	}
	// The later bind on a key wins, a modifier by any of its names; axiom's
	// file left out
	eq(t, js(NiriBinds(r.Files, false)), `[{"modmask":64,"key":"T","keycode":0,"submap":"","description":"spawn \"b\""},`+
		`{"modmask":64,"key":"Y","keycode":0,"submap":"","description":"spawn \"a\""},`+
		`{"modmask":68,"key":"Q","keycode":0,"submap":"","description":"spawn \"q2\""}]`)
}

func TestNiriSkipHeaderAndInfo(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "user", "a.kdl"), "layout {\n    gaps 4\n}\nbinds {\n    Mod+A { spawn \"a\"; }\n}\n")
	main := filepath.Join(dir, "config.kdl")
	write(t, main, "// Generated by axiom\nbinds {\n    Mod+X { spawn \"axiom\"; }\n}\ninclude \"user/a.kdl\"\n"+
		"layout {\n    gaps 8\n    struts {\n        left 2\n    }\n}\ninput {\n    mod-key \"Alt\"\n    mod-key-nested \"Alt\"\n    keyboard {\n        xkb {\n"+
		"            layout \"us,de\"\n        }\n    }\n}\n")
	r, err := ResolveNiri(main, nil, "// Generated by axiom", env(nil))
	if err != nil {
		t.Fatal(err)
	}
	var keys []string
	for _, b := range NiriBinds(r.Files, false).Items {
		keys = append(keys, b.(*jsonx.Object).Value("key").(string))
	}
	eq(t, strings.Join(keys, "|"), "A")
	r, _ = ResolveNiri(main, nil, "", env(nil))
	eq(t, js(NiriInfo(r.Files, false)), `{"gaps":8,"struts":{"top":0,"right":0,"bottom":0,"left":2},"layouts":"us,de",`+
		`"blur":{"enabled":true,"passes":3,"offset":3},"modKey":"ALT"}`)
}

// A later file's blur block sets only what it names
func TestNiriInfoBlur(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "look.kdl"), "blur {\n    passes 2\n}\n")
	main := filepath.Join(dir, "config.kdl")
	write(t, main, "blur {\n    passes 4\n    offset 5\n}\ninclude \"look.kdl\"\n")
	r, _ := ResolveNiri(main, nil, "", env(nil))
	eq(t, js(NiriInfo(r.Files, false).Value("blur")), `{"enabled":true,"passes":2,"offset":5}`)
	write(t, main, "blur {\n    off\n}\n")
	r, _ = ResolveNiri(main, nil, "", env(nil))
	eq(t, js(NiriInfo(r.Files, false).Value("blur")), `{"enabled":false,"passes":3,"offset":3}`)
}

