import json
import re
import sys
from pathlib import Path

from qml_modules import ROOT, qml_files

SCHEMA_PATH = ROOT / "config/json/config.schema.json"
CONFIG_OUT = "docs/dev/config"
GEN_OUT = "docs/dev/generated"
NOTICE = "<!-- Generated by scripts/gen_docs.py; do not edit. Regenerate with `scripts/gen_docs.py`. -->"

# Unions loaded by name: definition, page name, directory of type files,
# where a type's settings live, and how its files read them
UNIONS = [
    ("BarWidget", "BarWidgets", "components/bar/widgets", "properties", "properties"),
    ("OverlayModule", "OverlayModules", "components/content", "properties", "properties"),
    ("OverlayView", "OverlayViews", "components/views", None, "viewConfig|viewConf"),
]
UNION_NAMES = {u[0]: u[1] for u in UNIONS}
# Plumbing every union member shares, documented once on its page
SHARED_KEYS = {"type", "visible", "layout", "place"}
# Sections whose fields are merged into each bar's `barConfig` (Bar.lookOf,
# Bar.enrichBarConfig), so widgets read them as barConfig.<key>
BARCONFIG_PATHS = ["BarStyle", "Bars[]"]
# Annotations shown elsewhere in a setting's line (or noise in a reference)
# A section page over this many chars is split by its top-level objects
SPLIT_AT = 16000
LEGEND = ("Each setting: `path` · type = default · enum/range/unit; then title: description; "
          "annotations; `read:` the reader member(s) (exact unless marked) and `in:` the files that use them.")
SKIP_KEYS = {"type", "title", "description", "default", "enum", "properties", "items",
             "additionalProperties", "required", "x-order", "x-enumLabels", "minimum",
             "maximum", "x-unit", "$ref", "oneOf", "const"}


def rel(path):
    return str(Path(path).relative_to(ROOT))


def short(value, limit=90):
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return text if len(text) <= limit else text[: limit - 1] + "…"


def first_sentence(text, limit=220):
    text = " ".join(text.split())
    match = re.search(r"(?<=[.!?])\s+(?=[A-Z`(])", text)
    if match:
        text = text[: match.start()]
    return text if len(text) <= limit else text[: limit - 1] + "…"


# ---------------------------------------------------------------- QML parsing

MEMBER = re.compile(
    r"^  (?:(readonly|required|default)\s+)*property\s+(\S+)\s+(\w+)\s*(?::\s*(.*))?$"
    r"|^  signal\s+(\w+)\s*(\([^)]*\))?"
    r"|^  function\s+(\w+)\s*(\([^)]*\))\s*(?::\s*([\w.<>]+))?")
ROOT_OBJECT = re.compile(r"^[A-Z][\w.]*\s*\{")


def parse_qml(path):
    """The root object's header comment and its direct members:
    [{kind, name, type, expr, comment}], kind property/signal/function."""
    lines = path.read_text().splitlines()
    header, members = "", []
    start = next((i for i, line in enumerate(lines) if ROOT_OBJECT.match(line)), None)
    if start is None:
        return header, members
    j = start - 1
    while j >= 0 and not lines[j].strip():
        j -= 1
    block = []
    if j >= 0 and lines[j].rstrip().endswith("*/"):
        while j >= 0:
            block.insert(0, lines[j].strip().removeprefix("/**").removeprefix("/*").removesuffix("*/").lstrip("* ").strip())
            if "/*" in lines[j]:
                break
            j -= 1
    while j >= 0 and lines[j].startswith("//"):
        block.insert(0, lines[j][2:].strip())
        j -= 1
    header = " ".join(block)

    comment = []
    i = start + 1
    while i < len(lines):
        line = lines[i]
        if line.startswith("  //"):
            comment.append(line.strip()[2:].strip())
            i += 1
            continue
        match = MEMBER.match(line)
        if not match:
            if line.startswith("  ") and not line.startswith("   ") and line.strip() not in ("}", ""):
                comment = []
            elif not line.strip():
                comment = []
            i += 1
            continue
        body = [match.group(4) or ""]
        i += 1
        while i < len(lines) and not re.match(r"^  [^ })\]]", lines[i]) and lines[i] != "}":
            body.append(lines[i].strip())
            i += 1
        if match.group(3):
            members.append({"kind": "property", "name": match.group(3), "type": match.group(2),
                            "readonly": "readonly" in line.split("property")[0],
                            "expr": " ".join(body), "comment": " ".join(comment)})
        elif match.group(5):
            members.append({"kind": "signal", "name": match.group(5), "type": match.group(6) or "()",
                            "expr": "", "comment": " ".join(comment)})
        else:
            members.append({"kind": "function", "name": match.group(7), "type": match.group(8)
                            + (": " + match.group(9) if match.group(9) else ""),
                            "expr": " ".join(body), "comment": " ".join(comment)})
        comment = []
    return header, members


# ------------------------------------------------------------ config readers

CONFIG_REF = re.compile(r"ConfigManager\.(?:config|previews)\.(\w+)((?:\??\.\w+)*)")
PATH_REF = re.compile(r"@(\w+)((?:\??\.\w+)*)")


def config_paths(expr):
    return {(s + p.replace("?.", ".")) for s, p in PATH_REF.findall(expr)}


def load_readers():
    """{reader: {file, section(s), members: {name: {paths, exact, ...}}}}"""
    readers = {}
    for path in sorted((ROOT / "config").glob("*.qml")):
        header, members = parse_qml(path)
        # Aliases of a section: members whose whole value is the section
        aliases = {}
        for m in members:
            if m["kind"] != "property":
                continue
            expr = m["expr"].strip()
            refs = CONFIG_REF.findall(expr)
            if refs and all(not p for _, p in refs) and re.fullmatch(
                    r"ConfigManager\.(config|previews)\.\w+(\s*\?\?\s*ConfigManager\.(config|previews)\.\w+)?", expr):
                aliases[m["name"]] = refs[0][0]
        if not aliases and not any(CONFIG_REF.search(m["expr"]) for m in members):
            continue

        def normalize(expr):
            expr = CONFIG_REF.sub(lambda mo: "@" + mo.group(1) + mo.group(2), expr)
            for name, section in aliases.items():
                expr = re.sub(r"(?<![\w.@])(?:root\.)?" + name + r"\b", "@" + section, expr)
            return expr

        table = {}
        for m in members:
            norm = normalize(m["expr"])
            table[m["name"]] = dict(m, norm=norm, paths=config_paths(norm))
        # Members built from private helpers (`_jsonX: JSON.stringify(_c.x)`)
        # read what those read
        for _ in range(3):
            for name, m in table.items():
                for other, o in table.items():
                    if other != name and other.startswith("_") and re.search(r"(?<![\w.])(?:root\.)?" + other + r"\b", m["norm"]):
                        m["paths"] |= o["paths"]
        for name, m in table.items():
            m["exact"] = len(m["paths"]) == 1 and re.fullmatch(r"@[\w.?]+", m["norm"].strip()) is not None
            m["alias"] = name in aliases
        readers[path.stem] = {"file": rel(path), "header": header, "members": table,
                              "sections": sorted({p.split(".")[0] for m in table.values() for p in m["paths"]})}
    return readers


# --------------------------------------------------------------- usage index

class Usage:
    def __init__(self):
        raw = {rel(p): p.read_text() for p in qml_files()}
        # `// reads: Section.path, …` marks a read grep can't see (by key
        # name, a whole object handed to a helper); `*` matches any part
        self.markers = []
        for f, text in raw.items():
            for line in re.findall(r"//\s*reads:\s*(.+)", text):
                for pattern in re.sub(r"\([^)]*\)", "", line).split(","):
                    if pattern.strip():
                        self.markers.append((pattern.strip().replace("[]", ""), f))
        # Line comments out, so a mention in prose isn't a use
        self.files = {f: re.sub(r"(?m)(^|\s)//.*$", "", text) for f, text in raw.items()}

    def marked(self, path):
        plain = path.replace("[]", "")
        return sorted({f for pattern, f in self.markers if fnmatch.fnmatchcase(plain, pattern)})

    def of(self, pattern, exclude=()):
        regex = re.compile(pattern)
        return sorted(f for f, text in self.files.items() if f not in exclude and regex.search(text))

    def member(self, reader, name, own):
        """Files reading `Reader.name` (not `x.Reader.name`), but `own`."""
        if not hasattr(self, "_refs"):
            # One pass over every file instead of a search per member
            ref = re.compile(r"(?<![\w.])([A-Z]\w*)\.(\w+)")
            self._refs = {f: set(ref.findall(text)) for f, text in self.files.items()}
        return sorted(f for f, refs in self._refs.items() if f != own and (reader, name) in refs)


# ------------------------------------------------------------- schema walking

def resolve(schema, node):
    while "$ref" in node:
        node = schema["definitions"][node["$ref"].split("/")[-1]]
    return node


def ref_name(node):
    return node.get("$ref", "").split("/")[-1] or None


def walk(schema, node, path, out, depth=0):
    """Flatten a schema node into [(path, node, kind)] leaves; kind is
    'leaf', 'union' (one of a loaded-by-name union) or 'object'."""
    name = ref_name(node)
    if name in UNION_NAMES:
        out.append((path, node, "union"))
        return
    node = resolve(schema, node)
    if node.get("type") == "object" and "properties" in node and depth < 8:
        out.append((path, node, "object"))
        for key, child in node["properties"].items():
            walk(schema, child, f"{path}.{key}", out, depth + 1)
    elif node.get("type") == "array" and isinstance(node.get("items"), dict):
        items = node["items"]
        item = resolve(schema, items)
        if ref_name(items) in UNION_NAMES or (item.get("type") == "object" and "properties" in item):
            out.append((path, node, "leaf"))
            walk(schema, items, f"{path}[]", out, depth + 1)
        else:
            out.append((path, node, "leaf"))
    else:
        out.append((path, node, "leaf"))


def type_of(schema, node):
    node = resolve(schema, node)
    kind = node.get("type")
    if isinstance(kind, list):
        kind = "|".join(kind)
    if kind == "array":
        items = node.get("items", {})
        inner = UNION_NAMES.get(ref_name(items)) or ref_name(items) or type_of(schema, items) if isinstance(items, dict) else "any"
        return f"array<{inner}>"
    if "const" in node:
        return f"const {short(node['const'])}"
    return kind or ("enum" if "enum" in node else "any")


def describe(schema, node):
    """The one-line facts of a setting: type, default, range, enum, unit."""
    node = resolve(schema, node)
    parts = [type_of(schema, node)]
    if "default" in node:
        parts[0] += " = " + short(node["default"], 70)
    if "enum" in node:
        parts.append("enum " + "|".join(str(v) for v in node["enum"]))
    if "minimum" in node or "maximum" in node:
        parts.append(f"{node.get('minimum', '')}–{node.get('maximum', '')}")
    if "x-unit" in node:
        parts.append(node["x-unit"])
    return " · ".join(parts)


def annotations(node):
    return ", ".join(f"{k}={short(v, 70)}" for k, v in node.items()
                     if k not in SKIP_KEYS and (k.startswith("x-") or k in ("pattern", "format", "minItems", "maxItems")))


def text_of(node):
    title = node.get("title", "")
    desc = " ".join(node.get("description", "").split())
    return f"{title}: {desc}" if title and desc else title or desc


def join_files(files, limit=14):
    if not files:
        return "none found"
    shown = ", ".join(f"`{f}`" for f in files[:limit])
    return shown + (f" (+{len(files) - limit} more)" if len(files) > limit else "")


# ----------------------------------------------------------- config reference

class ConfigReference:
    def __init__(self, schema, readers, usage):
        self.schema, self.readers, self.usage = schema, readers, usage
        self.member_users = {}
        self.inside = set()
        for reader, info in readers.items():
            own = usage.files[info["file"]]
            for name, m in info["members"].items():
                if name.startswith("_"):
                    continue
                users = usage.member(reader, name, info["file"])
                if not users:
                    # A marker naming what it reads stands for a use
                    users = sorted({f for p in m["paths"] for f in usage.marked(p)})
                self.member_users[(reader, name)] = users
                # Used by the reader's own other members
                if len(re.findall(r"(?<![\w])" + name + r"\b", own)) > 1:
                    self.inside.add((reader, name))
        # Files outside config/ reading ConfigManager.config / previews
        self.direct = {}
        for f, text in usage.files.items():
            if f.startswith("config/"):
                continue
            for s, p in CONFIG_REF.findall(text):
                self.direct.setdefault(s + p.replace("?.", "."), set()).add(f)

    def reader_for(self, section):
        for reader, info in self.readers.items():
            if section in info["sections"]:
                return reader
        return None

    def members_for(self, path):
        """[(reader, member, how)] for a dotted setting path; how is
        'exact', 'computed', 'whole' (an ancestor passed whole) or 'part'."""
        plain = path.replace("[]", "")
        found = []
        for reader, info in self.readers.items():
            for name, m in info["members"].items():
                if name.startswith("_"):
                    continue
                for p in m["paths"]:
                    if p == plain:
                        found.append((reader, name, "exact" if m["exact"] else "computed"))
                    elif plain.startswith(p + "."):
                        found.append((reader, name, "whole"))
                    elif p.startswith(plain + "."):
                        found.append((reader, name, "part"))
                    else:
                        continue
                    break
        order = {"exact": 0, "computed": 1, "part": 2, "whole": 3}
        return sorted(set(found), key=lambda r: (order[r[2]], r[0], r[1]))

    def entry_scope(self, path):
        """Files that handle the entries of the list `path` is in: those
        using the list's reader member, and the component folders named
        after the section or the list."""
        array = path.split("[]", 1)[0]
        names = {n.lower() for n in (array.split(".")[0], array.split(".")[-1])}
        names |= {n[:-1] for n in names if n.endswith("s")}
        scope = set()
        for reader, name, _ in self.members_for(array):
            scope.update(self.member_users.get((reader, name), []))
            scope.add(self.readers[reader]["file"])
        for f in self.usage.files:
            if any(part.lower() in names for part in Path(f).parts[:-1]) or Path(f).stem.lower() in names:
                scope.add(f)
        return sorted(scope)

    def leaf_line(self, path, node, kind):
        node_r = resolve(self.schema, node)
        last = path.split(".")[-1].replace("[]", "")
        if kind == "union":
            page = UNION_NAMES[ref_name(node)]
            return [f"- **`{path}`**: one of the [{page}]({page}.md) types (discriminated by `type`)"]
        lines = [f"- **`{path}`** · {describe(self.schema, node)}"]
        text = text_of(node_r)
        if text:
            lines.append(f"  - {text}")
        ann = annotations(node_r)
        if ann:
            lines.append(f"  - {ann}")
        if kind == "object":
            return lines
        members = self.members_for(path)
        read = []
        files = set()
        for reader, name, how in members:
            if how == "whole" and any(h != "whole" for _, _, h in members):
                continue
            label = f"`{reader}.{name}`" + ("" if how == "exact" else f" ({how})")
            read.append(label)
            users = self.member_users.get((reader, name), [])
            if how == "whole":
                users = [f for f in users if re.search(r"\." + re.escape(last) + r"\b", self.usage.files[f])]
            files.update(users)
            files.add(self.readers[reader]["file"]) if not users else None
        plain = path.replace("[]", "")
        parts = plain.split(".")
        for i in range(2, len(parts) + 1):
            files.update(self.direct.get(".".join(parts[:i]), ()))
        if any(path.startswith(p + ".") for p in BARCONFIG_PATHS):
            files.update(self.usage.of(r"barConfig\??\." + re.escape(last) + r"\b"))
            read.append(f"`barConfig.{last}`")
        if "[]" in path and not (files - {r["file"] for r in self.readers.values()}):
            # An entry field: entries are passed on as whole objects and read
            # (or copied into same-named properties) in the feature's files
            files = set()
            files.update(f for f in self.entry_scope(path) if re.search(r"\??\." + re.escape(last) + r"\b", self.usage.files[f]))
            read = [r for r in read if "(whole)" not in r] + ["entry field, name match"]
            if not files:
                # Last resort: a distinctive key read anywhere (pure helpers
                # like HyprLua get entries handed to them)
                anywhere = self.usage.of(r"\??\." + re.escape(last) + r"\b")
                if 0 < len(anywhere) <= 6:
                    files.update(anywhere)
                    read[-1] = "entry field, name match repo-wide"
        marked = self.usage.marked(path)
        if marked:
            files.update(marked)
            read.append("`// reads:` marker")
        if read or files:
            lines.append(f"  - read: {', '.join(read) or 'directly'} · in: {join_files(sorted(files))}")
        else:
            lines.append("  - read: no reader member or direct use found")
        return lines

    def header(self, section, title, extra=()):
        node = self.schema["properties"][section]
        reader = self.reader_for(section)
        info = self.readers.get(reader)
        out = [NOTICE, f"# Config: {title}", ""]
        out.append(f"> **Reader:** `{reader}` (`{info['file']}`)" if info else "> **Reader:** none")
        out.append(f"> **Schema:** `config/json/config.schema.json` → `properties.{section}`"
                   + (f" · category {node['x-category']}" if "x-category" in node else "")
                   + (f" · scope {node['x-scope']}" if "x-scope" in node else ""))
        out += list(extra) + [""]
        return out

    def leaves_lines(self, leaves):
        out, current = [], None
        for path, child, kind in leaves:
            heading = path if kind == "object" else path.rsplit(".", 1)[0]
            if heading != current:
                out += ["", f"### `{heading}`", ""]
                current = heading
            out += self.leaf_line(path, child, kind)
        return out

    def section_pages(self, section):
        """The section's page, split into one page per top-level object or
        entry list when it would be over SPLIT_AT chars."""
        node = self.schema["properties"][section]
        reader = self.reader_for(section)
        info = self.readers.get(reader)
        extra = []
        whole = sorted(self.direct.get(section, ()))
        if whole:
            extra.append(f"> **Read whole by:** {join_files(whole)}")
        intro = []
        if text_of(node) and text_of(node) != section:
            intro += [text_of(node), ""]
        intro += [LEGEND, ""]
        leaves = []
        walk(self.schema, node, section, leaves)
        leaves = leaves[1:]
        members = []
        if info:
            members = ["", "### Reader members", "", f"Every public member of `{reader}`, with the files that use it.", ""]
            for name, m in info["members"].items():
                if name.startswith("_") or m["kind"] == "signal":
                    continue
                head = f"- `{reader}.{name}" + (f"{m['type']}`" if m["kind"] == "function" else f"` ({m['type']})")
                if m["comment"]:
                    head += f": {first_sentence(m['comment'], 160)}"
                users = self.member_users.get((reader, name), [])
                where = join_files(users, 10) if users or (reader, name) not in self.inside else "only inside the reader"
                members += [head, f"  - in: {where}"]
        body = self.leaves_lines(leaves)
        page = self.header(section, section, extra) + intro + body + members
        text = "\n".join(page).rstrip() + "\n"
        if len(text) <= SPLIT_AT:
            return {f"{CONFIG_OUT}/{section}.md": text}
        # Split: a child with a subtree gets its own page, again if needed
        pages, parts = {}, []
        top = self.split(section, section, leaves, pages, parts)
        links = ["", "### Parts", ""] + [f"- [`{n}`]({n}.md)" for n in parts]
        pages[f"{CONFIG_OUT}/{section}.md"] = "\n".join(
            self.header(section, section, extra) + intro + links + self.leaves_lines(top) + members).rstrip() + "\n"
        return pages

    def split(self, section, prefix, leaves, pages, parts):
        """Group `leaves` (all under `prefix`) by their next key; groups of
        more than one leaf become `<prefix>.<key>` pages, split again when
        still over SPLIT_AT. Returns the leaves left on the parent page."""
        groups = {}
        for leaf in leaves:
            rest = leaf[0][len(prefix):].lstrip("[]").lstrip(".")
            groups.setdefault(rest.split(".")[0].replace("[]", ""), []).append(leaf)
        left = []
        for key, group in groups.items():
            if len(group) < 2:
                left += group
                continue
            name = f"{prefix}.{key}"
            sub_prefix = group[0][0] if group[0][0].replace("[]", "") == name.replace("[]", "") else name
            text = "\n".join(self.leaves_lines(group))
            own = group
            if len(text) > SPLIT_AT:
                own = [group[0]] + self.split(section, sub_prefix, group[1:], pages, parts)
            parts.append(name)
            parent = prefix if prefix != section else section
            pages[f"{CONFIG_OUT}/{name}.md"] = "\n".join(
                self.header(section, name, [f"> **Part of:** [{parent}]({parent}.md)"]) + [LEGEND]
                + self.leaves_lines(own)).rstrip() + "\n"
        return left

    def union_pages(self, union, page, directory, settings_key, read_as):
        """An index of the union's types and one page per type."""
        defs = self.schema["definitions"]
        folder = f"{CONFIG_OUT}/{page}"
        index = [NOTICE, f"# Config: {page}", "",
                 f"> **Schema:** `definitions.{union}.oneOf`, discriminated by `type` · **Files:** `{directory}/<Type>/<Type>.qml`", "",
                 f"Every `{union}` type, one page each: its file, annotations, and its own settings with the files that read them. "
                 f"Shared keys ({', '.join('`' + k + '`' for k in sorted(SHARED_KEYS))}) are left out.", "",
                 "| Type | Label | Annotations |", "|---|---|---|"]
        pages = {}
        # What every type of the root shares (base/, and content's parts/)
        shared = [rel(p) for d in ("base", "parts") for p in sorted((ROOT / directory / d).rglob("*.qml"))]
        all_types = self._union_types()
        for option in defs[union]["oneOf"]:
            def_name = ref_name(option)
            node = resolve(self.schema, option)
            name = node["properties"]["type"]["const"]
            label = node["properties"]["type"].get("description", "")
            file = f"{directory}/{name}/{name}.qml"
            ann = annotations(node)
            index.append(f"| [{name}]({page}/{name}.md) | {label} | {ann} |")
            out = [NOTICE, f"# {page}: {name}", ""]
            out.append(f"> **File:** `{file}`" + ("" if (ROOT / file).exists() else " (missing)")
                       + f" · **Schema:** `definitions.{def_name}`" + (f" · **Label:** {label}" if label else ""))
            if ann:
                out.append(f"> **Annotations:** {ann}")
            out += ["", f"Settings are read as `{read_as.split('|')[0]}.<key>`.", ""]
            settings = node["properties"].get(settings_key, {}) if settings_key else node
            settings = resolve(self.schema, settings)
            leaves = []
            for key, child in settings.get("properties", {}).items():
                if not settings_key and key in SHARED_KEYS:
                    continue
                walk(self.schema, child, key, leaves)
            if not leaves:
                out.append("No settings of its own.")
            # The type's folder, its own parts first, then what it shares
            folder_files = [rel(p) for p in sorted((ROOT / directory / name).rglob("*.qml")) if rel(p) != file]
            scope = [file] + folder_files + shared
            for path, child, kind in leaves:
                child_r = resolve(self.schema, child)
                out.append(f"- **`{path}`** · {describe(self.schema, child)}")
                text = text_of(child_r)
                if text:
                    out.append(f"  - {text}")
                ann = annotations(child_r)
                if ann:
                    out.append(f"  - {ann}")
                if kind == "leaf":
                    top = path.split(".")[0].replace("[]", "")
                    hits = [f for f in scope if f in self.usage.files and re.search(
                        r"(?:" + read_as + r")\??\." + re.escape(top) + r"\b", self.usage.files[f])]
                    if not hits:
                        # Read generically (e.g. showPopout through
                        # EdgeMenusConfig.opensOwnPopout), outside any type file
                        type_paths = {f"{d}/{n}/{n}.qml" for _, _, d, _, _ in UNIONS for n in all_types}
                        anywhere = [f for f in self.usage.of(r"\??\." + re.escape(top) + r"\b") if f not in type_paths]
                        if 0 < len(anywhere) <= 6:
                            hits = anywhere
                            out.append(f"  - in (generic, name match): {join_files(hits, 6)}")
                            continue
                    out.append(f"  - in: {join_files(hits, 6)}")
            pages[f"{folder}/{name}.md"] = "\n".join(out).rstrip() + "\n"
        pages[f"{CONFIG_OUT}/{page}.md"] = "\n".join(index).rstrip() + "\n"
        return pages

    def _union_types(self):
        if not hasattr(self, "_types"):
            self._types = set()
            for u, *_ in UNIONS:
                for option in self.schema["definitions"][u]["oneOf"]:
                    self._types.add(resolve(self.schema, option)["properties"]["type"]["const"])
        return self._types

    def index_page(self, sections):
        out = [NOTICE, "# Config reference", "",
               "Generated from `config/json/config.schema.json` and the readers in `config/`. "
               "One file per section: every setting's type, default, annotations, description, "
               "the reader member that exposes it, and the files that use it (found by name, file level). "
               "Find a setting with `grep -rn 'Section.key' docs/dev/config/`. "
               "How the schema and annotations work: [schema-annotations](../core/schema-annotations.md).", "",
               "| Section | Reader | Category |", "|---|---|---|"]
        for section in sections:
            node = self.schema["properties"][section]
            reader = self.reader_for(section)
            info = self.readers.get(reader)
            out.append(f"| [{section}]({section}.md) | " + (f"`{reader}` (`{info['file']}`)" if info else "none")
                       + f" | {node.get('x-category', '')} |")
        out += ["", "Loaded-by-name types:", ""]
        for union, page, directory, *_ in UNIONS:
            n = len(self.schema["definitions"][union]["oneOf"])
            out.append(f"- [{page}]({page}.md): {n} `{union}` types, files in `{directory}/`")
        return "\n".join(out) + "\n"


