#!/usr/bin/env python3
"""Generate the reference docs that are derived from the code.

  docs/dev/config/       one file per config section: every setting's path,
                         type, default, annotations, description, the reader
                         member that exposes it and the files that use it;
                         plus BarWidgets / OverlayModules / OverlayViews
  docs/dev/generated/    files.md (every QML file's purpose comment),
                         ipc.md (every IpcTarget), rpc.md (the shell <->
                         daemon methods and pushes), layers.md (layer-rule
                         stacking, from LayerStack.layers), api/<Name>.md (the
                         public members of each service and config reader)

  scripts/gen_docs.py            write them (stale files removed); exit 1,
                                 writing nothing, when the shell calls or
                                 listens to something the daemon lacks
  scripts/gen_docs.py --report   also list reader members nothing uses

Usages are file level (no line numbers) and found by name, so they're a map
to start from, not a proof: a member read dynamically (`Reader[key]`) or off
an entry variable shows as unused or as a name match.
"""
